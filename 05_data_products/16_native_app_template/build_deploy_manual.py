"""Regenerate deploy_manual.sql from the files in ./app.

deploy_manual.sql embeds the app files (base64) so that the whole package can be
uploaded from a Snowsight worksheet, where PUT is not available. Run this after
editing anything under ./app:

    python3 build_deploy_manual.py
"""

import base64
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
APP_DIR = HERE / "app"
OUT = HERE / "deploy_manual.sql"

PKG = "DATA_HEALTH_CHECKER_PKG"
APP = "DATA_HEALTH_CHECKER_APP"
STAGE = f"{PKG}.STAGE_CONTENT.APP_STAGE"
STAGE_DIR = "v1"

# (path on stage relative to STAGE_DIR, local source file)
FILES = [
    ("manifest.yml", APP_DIR / "manifest.yml"),
    ("setup_script.sql", APP_DIR / "setup_script.sql"),
    ("README.md", APP_DIR / "README.md"),
    ("streamlit/app.py", APP_DIR / "streamlit" / "app.py"),
]


def b64_chunks(data: bytes, width: int = 76) -> str:
    """Return a Python expression joining base64 chunks, one per line."""
    encoded = base64.b64encode(data).decode("ascii")
    lines = [encoded[i:i + width] for i in range(0, len(encoded), width)]
    return "(\n" + "\n".join(f'        "{ln}"' for ln in lines) + "\n    )"


def build() -> str:
    file_entries = []
    for stage_path, src in FILES:
        file_entries.append(f'    "{stage_path}": {b64_chunks(src.read_bytes())},')
    files_block = "\n".join(file_entries)

    put_lines = "\n".join(
        f"-- PUT file://app/{p} @{STAGE}/{STAGE_DIR}/{p.rsplit('/', 1)[0] + '/' if '/' in p else ''} "
        f"AUTO_COMPRESS = FALSE OVERWRITE = TRUE;"
        for p, _ in FILES
    )

    return f"""/*=============================================================================
  ACCELERATOR 16 - Native App template: MANUAL deployment (no Snowflake CLI)
  App      : Data Health Checker
  Creates  : application package {PKG} (+ stage {STAGE})
             application {APP} (dev-mode install from staged files)
             optional: version V1_0 + default release directive
  Run as   : ACCOUNTADMIN for two account grants, then ACCEL_ADMIN
  Rerun    : safe - files are overwritten, the app is upgraded in place.
  GENERATED by build_deploy_manual.py from ./app - edit the app files and
  re-run the script instead of editing the base64 block below.
=============================================================================*/

-- ACCOUNTADMIN: CREATE APPLICATION PACKAGE / CREATE APPLICATION are account-level privileges
USE ROLE ACCOUNTADMIN;
GRANT CREATE APPLICATION PACKAGE ON ACCOUNT TO ROLE ACCEL_ADMIN;
GRANT CREATE APPLICATION         ON ACCOUNT TO ROLE ACCEL_ADMIN;

USE ROLE ACCEL_ADMIN;
USE WAREHOUSE ACCEL_WH;

------------------------------------------------------------------------------
-- 1. Application package and its stage
------------------------------------------------------------------------------
CREATE APPLICATION PACKAGE IF NOT EXISTS {PKG}
  COMMENT = 'Accelerator 16: Data Health Checker native app';
CREATE SCHEMA IF NOT EXISTS {PKG}.STAGE_CONTENT;
CREATE STAGE IF NOT EXISTS {STAGE}
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Native app source files';

------------------------------------------------------------------------------
-- 2. Upload the app files to @{STAGE}/{STAGE_DIR}/
--
--    Option A (SnowSQL or `snow sql`, run from this folder) - PUT does NOT
--    work in Snowsight worksheets:
{put_lines}
--
--    Option B (Snowsight worksheet) - the anonymous procedure below writes the
--    embedded copies of the files with session.file.put_stream.
--
--    Option C - Snowsight UI: Data > Databases > {PKG} > STAGE_CONTENT > Stages >
--    APP_STAGE > "+ Files", upload into folder {STAGE_DIR} (and {STAGE_DIR}/streamlit for app.py).
------------------------------------------------------------------------------
WITH UPLOAD_APP_FILES AS PROCEDURE ()
  RETURNS VARCHAR
  LANGUAGE PYTHON
  RUNTIME_VERSION = '3.11'
  PACKAGES = ('snowflake-snowpark-python')
  HANDLER = 'run'
AS
$$
import base64
import io

STAGE = "@{STAGE}/{STAGE_DIR}"
FILES = {{
{files_block}
}}


def run(session):
    written = []
    for path, b64 in FILES.items():
        data = base64.b64decode(b64)
        session.file.put_stream(io.BytesIO(data), f"{{STAGE}}/{{path}}", auto_compress=False, overwrite=True)
        written.append(f"{{path}} ({{len(data)}} bytes)")
    return "Uploaded: " + ", ".join(written)
$$
CALL UPLOAD_APP_FILES();

ALTER STAGE {STAGE} REFRESH;
LIST @{STAGE}/{STAGE_DIR}/;

------------------------------------------------------------------------------
-- 3. Install (or upgrade) the app in dev mode straight from the staged files
------------------------------------------------------------------------------
EXECUTE IMMEDIATE $$
DECLARE
    app_count NUMBER DEFAULT 0;
BEGIN
    SHOW APPLICATIONS LIKE '{APP}';
    SELECT COUNT(*) INTO :app_count FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));
    IF (app_count = 0) THEN
        CREATE APPLICATION {APP}
          FROM APPLICATION PACKAGE {PKG}
          USING '@{STAGE}/{STAGE_DIR}'
          COMMENT = 'Data Health Checker (dev install)';
        RETURN 'Application {APP} created';
    ELSE
        ALTER APPLICATION {APP} UPGRADE USING '@{STAGE}/{STAGE_DIR}';
        RETURN 'Application {APP} upgraded from staged files';
    END IF;
END;
$$;

------------------------------------------------------------------------------
-- 4. Bind a table to the app reference (what a consumer does in the Security tab)
------------------------------------------------------------------------------
CALL {APP}.CORE.REGISTER_SINGLE_REFERENCE(
    'consumer_table', 'ADD',
    SYSTEM$REFERENCE('TABLE', 'ACCEL_DB.DEMO.CUSTOMERS', 'PERSISTENT', 'SELECT'));   -- EDIT ME: table to profile

CALL {APP}.CORE.PROFILE_TABLE();
SELECT * FROM {APP}.DATA.PROFILE_RUNS ORDER BY RUN_TS DESC;
SELECT * FROM {APP}.CORE.LATEST_COLUMN_PROFILE ORDER BY ORDINAL;
-- Open the UI: Snowsight > Data Products > Apps > {APP}

------------------------------------------------------------------------------
-- 5. OPTIONAL: create version V1_0 and make it the default release
--    Works for packages with or without release channels.
------------------------------------------------------------------------------
EXECUTE IMMEDIATE $$
DECLARE
    create_version BOOLEAN DEFAULT FALSE;   -- EDIT ME: TRUE to create V1_0
    channel_count  NUMBER DEFAULT 0;
    version_count  NUMBER DEFAULT 0;
BEGIN
    IF (NOT create_version) THEN
        RETURN 'Versioning skipped (set create_version = TRUE).';
    END IF;

    SHOW VERSIONS IN APPLICATION PACKAGE {PKG};
    SELECT COUNT(*) INTO :version_count FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())) WHERE "version" = 'V1_0';
    IF (version_count > 0) THEN
        RETURN 'Version V1_0 already exists - add a patch with: ALTER APPLICATION PACKAGE {PKG} ADD PATCH FOR VERSION V1_0 USING ''@{STAGE}/{STAGE_DIR}'';';
    END IF;

    BEGIN
        SHOW RELEASE CHANNELS IN APPLICATION PACKAGE {PKG};
        SELECT COUNT(*) INTO :channel_count FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));
    EXCEPTION
        WHEN OTHER THEN
            channel_count := 0;   -- release channels not enabled / not available
    END;

    IF (channel_count > 0) THEN
        ALTER APPLICATION PACKAGE {PKG} REGISTER VERSION V1_0 USING '@{STAGE}/{STAGE_DIR}' LABEL = 'Data Health Checker 1.0';
        ALTER APPLICATION PACKAGE {PKG} MODIFY RELEASE CHANNEL DEFAULT ADD VERSION V1_0;
        ALTER APPLICATION PACKAGE {PKG} MODIFY RELEASE CHANNEL DEFAULT SET DEFAULT RELEASE DIRECTIVE VERSION = V1_0 PATCH = 0;
        RETURN 'V1_0 registered and set as DEFAULT release channel directive';
    ELSE
        ALTER APPLICATION PACKAGE {PKG} ADD VERSION V1_0 USING '@{STAGE}/{STAGE_DIR}' LABEL = 'Data Health Checker 1.0';
        ALTER APPLICATION PACKAGE {PKG} SET DEFAULT RELEASE DIRECTIVE VERSION = V1_0 PATCH = 0;
        RETURN 'V1_0 added and set as default release directive';
    END IF;
END;
$$;

SHOW VERSIONS IN APPLICATION PACKAGE {PKG};

/*----------------------------------------------------------------------------
  Install from the released version instead of staged files:
    DROP APPLICATION IF EXISTS {APP};
    CREATE APPLICATION {APP} FROM APPLICATION PACKAGE {PKG};                 -- default release directive
    CREATE APPLICATION {APP} FROM APPLICATION PACKAGE {PKG} USING VERSION V1_0 PATCH 0;   -- explicit

  Prepare for the Marketplace / external consumers (triggers the automated security scan):
    ALTER APPLICATION PACKAGE {PKG} SET DISTRIBUTION = EXTERNAL;
    SHOW VERSIONS IN APPLICATION PACKAGE {PKG};   -- check review_status = APPROVED

  Clean up:
    DROP APPLICATION IF EXISTS {APP};
    DROP APPLICATION PACKAGE IF EXISTS {PKG};
----------------------------------------------------------------------------*/
"""


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    print(f"Wrote {OUT}")
