CREATE SCHEMA IF NOT EXISTS DPDP;
USE SCHEMA DPDP;

------------------------------------------------------------------------------
-- 1. Scorecard: one row per control, with RAG status
------------------------------------------------------------------------------
CREATE OR REPLACE VIEW V_DPDP_COMPLIANCE_SCORECARD
  COMMENT = 'DPDP kit: control scorecard with RAG status'
AS
WITH inv AS (
    SELECT COUNT(*) AS PII_COLUMNS,
           COUNT(DISTINCT DATABASE_NAME || '.' || SCHEMA_NAME || '.' || TABLE_NAME) AS PII_TABLES,
           COUNT_IF(RISK_LEVEL = 'HIGH') AS HIGH_RISK_COLUMNS,
           DATEDIFF(DAY, MAX(LAST_SCANNED_AT), CURRENT_TIMESTAMP()::TIMESTAMP_NTZ) AS DAYS_SINCE_SCAN
    FROM ACCEL_DB.DPDP.V_PERSONAL_DATA_INVENTORY
),
cons AS (
    SELECT COUNT(DISTINCT DATA_PRINCIPAL_ID) AS PRINCIPALS,
           COUNT_IF(PURPOSE_CODE = 'MARKETING' AND EFFECTIVE_STATUS = 'ACTIVE')
             / NULLIF(COUNT_IF(PURPOSE_CODE = 'MARKETING'), 0) * 100 AS MARKETING_CONSENT_PCT,
           COUNT_IF(EFFECTIVE_STATUS = 'EXPIRED') AS EXPIRED_CONSENTS,
           COUNT_IF(NOTICE_VERSION <> 'NOTICE-v2.0-DPDP' AND EFFECTIVE_STATUS = 'ACTIVE') AS ACTIVE_ON_OLD_NOTICE
    FROM ACCEL_DB.DPDP.V_CONSENT_CURRENT
),
wd AS (
    SELECT COUNT(*) AS WITHDRAWALS_30D
    FROM ACCEL_DB.DPDP.CONSENT_REGISTER
    WHERE CONSENT_STATUS = 'WITHDRAWN' AND EVENT_TS >= DATEADD(DAY, -30, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ)
),
dsr AS (
    SELECT COUNT_IF(STATUS IN ('RECEIVED', 'IN_PROGRESS')) AS OPEN_REQUESTS,
           COUNT_IF(SLA_STATUS IN ('OVERDUE', 'BREACHED'))  AS SLA_BREACHES,
           AVG(IFF(STATUS = 'COMPLETED', AGE_HOURS, NULL)) / 24 AS AVG_DAYS_TO_CLOSE
    FROM ACCEL_DB.DPDP.V_DSR_SLA
),
ret AS (
    SELECT DATEDIFF(DAY, MAX(RUN_TS), CURRENT_TIMESTAMP()::TIMESTAMP_NTZ) AS DAYS_SINCE_RETENTION_RUN,
           MAX_BY(DRY_RUN, RUN_TS) AS LAST_RUN_WAS_DRY
    FROM ACCEL_DB.DPDP.RETENTION_RUN_LOG
),
pol AS (
    SELECT COUNT(*) AS POLICIES_ON_GOVERNED_VIEW
    FROM TABLE(ACCEL_DB.INFORMATION_SCHEMA.POLICY_REFERENCES(
        REF_ENTITY_NAME => 'ACCEL_DB.DPDP.V_CUSTOMER_PERSONAL_DATA', REF_ENTITY_DOMAIN => 'view'))
)
SELECT 'Inventory' AS AREA, 'Personal data columns discovered' AS CONTROL, inv.PII_COLUMNS::VARCHAR AS VALUE,
       IFF(inv.PII_COLUMNS > 0, 'GREEN', 'RED') AS RAG FROM inv
UNION ALL SELECT 'Inventory', 'Tables holding personal data', inv.PII_TABLES::VARCHAR, 'GREEN' FROM inv
UNION ALL SELECT 'Inventory', 'High-risk columns (IDs, financial, special)', inv.HIGH_RISK_COLUMNS::VARCHAR,
       IFF(inv.HIGH_RISK_COLUMNS > 0, 'AMBER', 'GREEN') FROM inv
UNION ALL SELECT 'Inventory', 'Days since last discovery scan', inv.DAYS_SINCE_SCAN::VARCHAR,
       CASE WHEN inv.DAYS_SINCE_SCAN <= 30 THEN 'GREEN' WHEN inv.DAYS_SINCE_SCAN <= 90 THEN 'AMBER' ELSE 'RED' END FROM inv
UNION ALL SELECT 'Consent', 'Data principals in consent register', cons.PRINCIPALS::VARCHAR, 'GREEN' FROM cons
UNION ALL SELECT 'Consent', 'Marketing consent rate %', TO_VARCHAR(ROUND(cons.MARKETING_CONSENT_PCT, 1)), 'GREEN' FROM cons
UNION ALL SELECT 'Consent', 'Expired consents still marked GRANTED', cons.EXPIRED_CONSENTS::VARCHAR,
       IFF(cons.EXPIRED_CONSENTS = 0, 'GREEN', 'AMBER') FROM cons
UNION ALL SELECT 'Consent', 'Active consents captured on pre-DPDP notice', cons.ACTIVE_ON_OLD_NOTICE::VARCHAR,
       IFF(cons.ACTIVE_ON_OLD_NOTICE = 0, 'GREEN', 'AMBER') FROM cons
UNION ALL SELECT 'Consent', 'Withdrawals in last 30 days', wd.WITHDRAWALS_30D::VARCHAR, 'GREEN' FROM wd
UNION ALL SELECT 'Rights', 'Open data principal requests', dsr.OPEN_REQUESTS::VARCHAR,
       IFF(dsr.OPEN_REQUESTS <= 10, 'GREEN', 'AMBER') FROM dsr
UNION ALL SELECT 'Rights', 'Requests overdue / closed late', dsr.SLA_BREACHES::VARCHAR,
       IFF(dsr.SLA_BREACHES = 0, 'GREEN', 'RED') FROM dsr
UNION ALL SELECT 'Rights', 'Average days to close', TO_VARCHAR(ROUND(dsr.AVG_DAYS_TO_CLOSE, 1)),
       IFF(dsr.AVG_DAYS_TO_CLOSE <= 15, 'GREEN', 'AMBER') FROM dsr
UNION ALL SELECT 'Retention', 'Days since last retention run', COALESCE(ret.DAYS_SINCE_RETENTION_RUN::VARCHAR, 'never'),
       CASE WHEN ret.DAYS_SINCE_RETENTION_RUN IS NULL THEN 'RED'
            WHEN ret.LAST_RUN_WAS_DRY THEN 'AMBER'
            WHEN ret.DAYS_SINCE_RETENTION_RUN <= 35 THEN 'GREEN' ELSE 'RED' END FROM ret
UNION ALL SELECT 'Access control', 'Policies on governed customer view', pol.POLICIES_ON_GOVERNED_VIEW::VARCHAR,
       IFF(pol.POLICIES_ON_GOVERNED_VIEW >= 2, 'GREEN', 'RED') FROM pol;

------------------------------------------------------------------------------
-- 2. Supporting views
------------------------------------------------------------------------------
CREATE OR REPLACE VIEW V_PII_BY_TABLE AS
SELECT DATABASE_NAME, SCHEMA_NAME, TABLE_NAME,
       COUNT(*) AS PII_COLUMNS,
       COUNT_IF(RISK_LEVEL = 'HIGH') AS HIGH_RISK_COLUMNS,
       LISTAGG(COLUMN_NAME || ' (' || SEMANTIC_CATEGORY || ')', ', ') WITHIN GROUP (ORDER BY COLUMN_NAME) AS COLUMNS
FROM ACCEL_DB.DPDP.V_PERSONAL_DATA_INVENTORY
GROUP BY 1, 2, 3;

CREATE OR REPLACE VIEW V_CONSENT_TREND AS
SELECT DATE_TRUNC('MONTH', EVENT_TS)::DATE AS MONTH, PURPOSE_CODE, CONSENT_STATUS, COUNT(*) AS EVENTS
FROM ACCEL_DB.DPDP.CONSENT_REGISTER
GROUP BY 1, 2, 3;

CREATE OR REPLACE VIEW V_DSR_SUMMARY AS
SELECT REQUEST_TYPE, STATUS, SLA_STATUS, COUNT(*) AS REQUESTS, ROUND(AVG(AGE_HOURS) / 24, 1) AS AVG_AGE_DAYS
FROM ACCEL_DB.DPDP.V_DSR_SLA
GROUP BY 1, 2, 3;

SELECT * FROM V_DPDP_COMPLIANCE_SCORECARD;
SELECT * FROM V_PII_BY_TABLE ORDER BY HIGH_RISK_COLUMNS DESC;
