/* =============================================================================
   05 LAKEHOUSE BLUEPRINT | 02_silver.sql
   SILVER = cleansed + conformed: deduplicated on business keys, trimmed and
   standardized values, explicit data types, deterministic surrogate keys
   (MD5 of the business key so they are stable across rebuilds), DQ flags.
   Run as: ACCEL_ADMIN.
============================================================================= */
USE ROLE ACCEL_ADMIN;
USE WAREHOUSE ACCEL_WH;
USE DATABASE ACCEL_DB;
CREATE SCHEMA IF NOT EXISTS SILVER;
USE SCHEMA SILVER;

CREATE OR REPLACE DYNAMIC TABLE SLV_CUSTOMERS
  TARGET_LAG = DOWNSTREAM
  WAREHOUSE = ACCEL_WH
  COMMENT = 'Conformed customers: 1 row per CUSTOMER_ID'
AS
SELECT
  MD5(TO_VARCHAR(CUSTOMER_ID))                          AS CUSTOMER_SK,
  CUSTOMER_ID::NUMBER(38,0)                             AS CUSTOMER_ID,
  TRIM(CUSTOMER_NAME)::VARCHAR                     AS CUSTOMER_NAME,
  TRIM(SEGMENT)::VARCHAR                   AS SEGMENT,
  TRIM(INDUSTRY)::VARCHAR                 AS INDUSTRY,
  TRIM(REGION)::VARCHAR                    AS REGION,
  TRIM(COUNTRY)::VARCHAR                            AS COUNTRY,
  CASE UPPER(TRIM(COUNTRY))
    WHEN 'INDIA' THEN 'IN' WHEN 'USA' THEN 'US' WHEN 'UK' THEN 'GB'
    WHEN 'GERMANY' THEN 'DE' WHEN 'JAPAN' THEN 'JP' WHEN 'SINGAPORE' THEN 'SG'
    ELSE 'XX' END::VARCHAR                           AS COUNTRY_CODE,
  INITCAP(TRIM(CITY))::VARCHAR                     AS CITY,
  LOWER(TRIM(EMAIL))::VARCHAR                      AS EMAIL,
  REGEXP_REPLACE(PHONE, '[^0-9+]', '')::VARCHAR     AS PHONE,
  UPPER(TRIM(PAN_NUMBER))::VARCHAR                  AS PAN_NUMBER,
  CREATED_DATE::DATE                                    AS CREATED_DATE,
  CREDIT_LIMIT::NUMBER(12,2)                            AS CREDIT_LIMIT,
  REGEXP_LIKE(LOWER(TRIM(EMAIL)), '^[a-z0-9._%+-]+@[a-z0-9.-]+[.][a-z]{2,}$') AS DQ_EMAIL_VALID
FROM ACCEL_DB.BRONZE.BRZ_CUSTOMERS
WHERE CUSTOMER_ID IS NOT NULL
QUALIFY ROW_NUMBER() OVER (PARTITION BY CUSTOMER_ID ORDER BY CREATED_DATE DESC NULLS LAST) = 1;

CREATE OR REPLACE DYNAMIC TABLE SLV_PRODUCTS
  TARGET_LAG = DOWNSTREAM
  WAREHOUSE = ACCEL_WH
AS
SELECT
  MD5(TO_VARCHAR(PRODUCT_ID))                 AS PRODUCT_SK,
  PRODUCT_ID::NUMBER(38,0)                    AS PRODUCT_ID,
  UPPER(TRIM(SKU))::VARCHAR               AS SKU,
  TRIM(PRODUCT_NAME)::VARCHAR            AS PRODUCT_NAME,
  TRIM(CATEGORY)::VARCHAR       AS CATEGORY,
  TRIM(SUB_CATEGORY)::VARCHAR   AS SUB_CATEGORY,
  TRIM(BRAND)::VARCHAR                   AS BRAND,
  UNIT_COST::NUMBER(10,2)                     AS UNIT_COST,
  LIST_PRICE::NUMBER(10,2)                    AS LIST_PRICE,
  (LIST_PRICE - UNIT_COST)::NUMBER(10,2)      AS STD_MARGIN,
  LAUNCH_DATE::DATE                           AS LAUNCH_DATE
FROM ACCEL_DB.BRONZE.BRZ_PRODUCTS
WHERE PRODUCT_ID IS NOT NULL
QUALIFY ROW_NUMBER() OVER (PARTITION BY PRODUCT_ID ORDER BY LAUNCH_DATE DESC NULLS LAST) = 1;

CREATE OR REPLACE DYNAMIC TABLE SLV_PLANTS
  TARGET_LAG = DOWNSTREAM
  WAREHOUSE = ACCEL_WH
AS
SELECT
  MD5(TO_VARCHAR(PLANT_ID))                   AS PLANT_SK,
  PLANT_ID::NUMBER(38,0)                      AS PLANT_ID,
  TRIM(PLANT_NAME)::VARCHAR              AS PLANT_NAME,
  INITCAP(TRIM(CITY))::VARCHAR           AS CITY,
  TRIM(COUNTRY)::VARCHAR                  AS COUNTRY,
  CAPACITY_UNITS_PER_DAY::NUMBER(12,0)        AS CAPACITY_UNITS_PER_DAY
FROM ACCEL_DB.BRONZE.BRZ_PLANTS
WHERE PLANT_ID IS NOT NULL
QUALIFY ROW_NUMBER() OVER (PARTITION BY PLANT_ID ORDER BY PLANT_NAME) = 1;

CREATE OR REPLACE DYNAMIC TABLE SLV_ORDERS
  TARGET_LAG = DOWNSTREAM
  WAREHOUSE = ACCEL_WH
AS
SELECT
  ORDER_ID::NUMBER(38,0)                      AS ORDER_ID,
  ORDER_DATE::DATE                            AS ORDER_DATE,
  CUSTOMER_ID::NUMBER(38,0)                   AS CUSTOMER_ID,
  PLANT_ID::NUMBER(38,0)                      AS PLANT_ID,
  TRIM(CHANNEL)::VARCHAR         AS CHANNEL,
  UPPER(TRIM(STATUS))::VARCHAR            AS ORDER_STATUS,
  UPPER(TRIM(CURRENCY))::VARCHAR           AS CURRENCY,
  ORDER_TOTAL::NUMBER(14,2)                   AS ORDER_TOTAL,
  UPPER(TRIM(STATUS)) IN ('DELIVERED', 'SHIPPED') AS IS_REVENUE_RECOGNISED
FROM ACCEL_DB.BRONZE.BRZ_ORDERS
WHERE ORDER_ID IS NOT NULL
QUALIFY ROW_NUMBER() OVER (PARTITION BY ORDER_ID ORDER BY ORDER_DATE DESC NULLS LAST) = 1;

CREATE OR REPLACE DYNAMIC TABLE SLV_ORDER_LINES
  TARGET_LAG = DOWNSTREAM
  WAREHOUSE = ACCEL_WH
AS
SELECT
  MD5(TO_VARCHAR(ORDER_ID) || '-' || TO_VARCHAR(LINE_NO)) AS ORDER_LINE_SK,
  ORDER_ID::NUMBER(38,0)                      AS ORDER_ID,
  LINE_NO::NUMBER(10,0)                       AS LINE_NO,
  PRODUCT_ID::NUMBER(38,0)                    AS PRODUCT_ID,
  QUANTITY::NUMBER(12,0)                      AS QUANTITY,
  UNIT_PRICE::NUMBER(10,2)                    AS UNIT_PRICE,
  COALESCE(DISCOUNT_PCT, 0)::NUMBER(5,2)      AS DISCOUNT_PCT,
  NET_AMOUNT::NUMBER(14,2)                    AS NET_AMOUNT,
  (QUANTITY > 0 AND NET_AMOUNT >= 0)          AS DQ_LINE_VALID
FROM ACCEL_DB.BRONZE.BRZ_ORDER_LINES
WHERE ORDER_ID IS NOT NULL AND LINE_NO IS NOT NULL
QUALIFY ROW_NUMBER() OVER (PARTITION BY ORDER_ID, LINE_NO ORDER BY NET_AMOUNT DESC NULLS LAST) = 1;

CREATE OR REPLACE DYNAMIC TABLE SLV_INVENTORY_SNAPSHOTS
  TARGET_LAG = DOWNSTREAM
  WAREHOUSE = ACCEL_WH
AS
SELECT
  SNAPSHOT_DATE::DATE                         AS SNAPSHOT_DATE,
  PLANT_ID::NUMBER(38,0)                      AS PLANT_ID,
  PRODUCT_ID::NUMBER(38,0)                    AS PRODUCT_ID,
  GREATEST(COALESCE(ON_HAND_QTY, 0), 0)::NUMBER(12,0) AS ON_HAND_QTY,
  REORDER_POINT::NUMBER(12,0)                 AS REORDER_POINT,
  SAFETY_STOCK::NUMBER(12,0)                  AS SAFETY_STOCK
FROM ACCEL_DB.BRONZE.BRZ_INVENTORY_SNAPSHOTS
WHERE SNAPSHOT_DATE IS NOT NULL
QUALIFY ROW_NUMBER() OVER (PARTITION BY SNAPSHOT_DATE, PLANT_ID, PRODUCT_ID ORDER BY ON_HAND_QTY DESC NULLS LAST) = 1;

CREATE OR REPLACE DYNAMIC TABLE SLV_GL_JOURNAL
  TARGET_LAG = DOWNSTREAM
  WAREHOUSE = ACCEL_WH
AS
SELECT
  JOURNAL_ID::VARCHAR                     AS JOURNAL_ID,
  LINE_NO::NUMBER(10,0)                       AS LINE_NO,
  POSTING_DATE::DATE                          AS POSTING_DATE,
  ENTRY_TIMESTAMP::TIMESTAMP_NTZ              AS ENTRY_TIMESTAMP,
  UPPER(TRIM(ENTITY))::VARCHAR            AS ENTITY,
  TRIM(ACCOUNT_CODE)::VARCHAR             AS ACCOUNT_CODE,
  TRIM(ACCOUNT_NAME)::VARCHAR            AS ACCOUNT_NAME,
  TRIM(ACCOUNT_TYPE)::VARCHAR             AS ACCOUNT_TYPE,
  TRIM(COST_CENTER)::VARCHAR              AS COST_CENTER,
  AMOUNT::NUMBER(16,2)                        AS AMOUNT,
  IFF(AMOUNT > 0, AMOUNT, 0)::NUMBER(16,2)    AS DEBIT_AMOUNT,
  IFF(AMOUNT < 0, -AMOUNT, 0)::NUMBER(16,2)   AS CREDIT_AMOUNT,
  UPPER(TRIM(CURRENCY))::VARCHAR           AS CURRENCY,
  DESCRIPTION::VARCHAR                  AS DESCRIPTION,
  CREATED_BY::VARCHAR                    AS CREATED_BY,
  APPROVED_BY::VARCHAR                   AS APPROVED_BY,
  UPPER(TRIM(SOURCE))::VARCHAR            AS SOURCE
FROM ACCEL_DB.BRONZE.BRZ_GL_JOURNAL
WHERE JOURNAL_ID IS NOT NULL
QUALIFY ROW_NUMBER() OVER (PARTITION BY JOURNAL_ID, LINE_NO ORDER BY ENTRY_TIMESTAMP DESC NULLS LAST) = 1;

