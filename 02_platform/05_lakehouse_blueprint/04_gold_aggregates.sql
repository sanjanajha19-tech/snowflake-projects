USE ROLE ACCEL_ADMIN;
USE WAREHOUSE ACCEL_WH;
USE DATABASE ACCEL_DB;
CREATE SCHEMA IF NOT EXISTS GOLD;
USE SCHEMA GOLD;

-- Monthly revenue by region and category (recognised revenue only)
CREATE OR REPLACE DYNAMIC TABLE AGG_MONTHLY_REVENUE_REGION_CATEGORY
  TARGET_LAG = '1 hour'
  WAREHOUSE = ACCEL_WH
AS
SELECT
  DATE_TRUNC('MONTH', f.ORDER_DATE)        AS MONTH_START,
  c.REGION,
  p.CATEGORY,
  f.CURRENCY,
  COUNT(DISTINCT f.ORDER_ID)               AS ORDERS,
  SUM(f.QUANTITY)                          AS UNITS,
  SUM(f.GROSS_AMOUNT)                      AS GROSS_REVENUE,
  SUM(f.NET_AMOUNT)                        AS NET_REVENUE,
  SUM(f.COST_AMOUNT)                       AS COST,
  SUM(f.MARGIN_AMOUNT)                     AS MARGIN,
  ROUND(SUM(f.MARGIN_AMOUNT) / NULLIF(SUM(f.NET_AMOUNT), 0) * 100, 2) AS MARGIN_PCT
FROM ACCEL_DB.GOLD.FACT_SALES f
JOIN ACCEL_DB.GOLD.DIM_CUSTOMER c ON c.CUSTOMER_SK = f.CUSTOMER_SK
JOIN ACCEL_DB.GOLD.DIM_PRODUCT  p ON p.PRODUCT_SK  = f.PRODUCT_SK
WHERE f.IS_REVENUE_RECOGNISED
GROUP BY 1, 2, 3, 4;

-- Monthly margin by channel and category, incl. discount leakage
CREATE OR REPLACE DYNAMIC TABLE AGG_MONTHLY_MARGIN
  TARGET_LAG = '1 hour'
  WAREHOUSE = ACCEL_WH
AS
SELECT
  DATE_TRUNC('MONTH', f.ORDER_DATE)        AS MONTH_START,
  f.CHANNEL,
  p.CATEGORY,
  f.CURRENCY,
  SUM(f.NET_AMOUNT)                        AS NET_REVENUE,
  SUM(f.COST_AMOUNT)                       AS COST,
  SUM(f.MARGIN_AMOUNT)                     AS MARGIN,
  SUM(f.GROSS_AMOUNT - f.NET_AMOUNT)       AS DISCOUNT_LEAKAGE,
  ROUND(SUM(f.MARGIN_AMOUNT) / NULLIF(SUM(f.NET_AMOUNT), 0) * 100, 2) AS MARGIN_PCT
FROM ACCEL_DB.GOLD.FACT_SALES f
JOIN ACCEL_DB.GOLD.DIM_PRODUCT p ON p.PRODUCT_SK = f.PRODUCT_SK
WHERE f.IS_REVENUE_RECOGNISED
GROUP BY 1, 2, 3, 4;

-- Monthly P&L by entity from the GL
CREATE OR REPLACE DYNAMIC TABLE AGG_MONTHLY_PNL
  TARGET_LAG = '1 hour'
  WAREHOUSE = ACCEL_WH
AS
SELECT
  DATE_TRUNC('MONTH', POSTING_DATE)                          AS MONTH_START,
  ENTITY,
  CURRENCY,
  SUM(IFF(ACCOUNT_TYPE = 'Revenue', PNL_AMOUNT, 0))          AS REVENUE,
  SUM(IFF(ACCOUNT_TYPE = 'COGS', PNL_AMOUNT, 0))             AS COGS,
  SUM(IFF(ACCOUNT_TYPE = 'Opex', PNL_AMOUNT, 0))             AS OPEX,
  SUM(IFF(ACCOUNT_TYPE = 'Revenue', PNL_AMOUNT, 0))
    - SUM(IFF(ACCOUNT_TYPE = 'COGS', PNL_AMOUNT, 0))         AS GROSS_PROFIT,
  SUM(IFF(ACCOUNT_TYPE = 'Revenue', PNL_AMOUNT, 0))
    - SUM(IFF(ACCOUNT_TYPE IN ('COGS', 'Opex'), PNL_AMOUNT, 0)) AS OPERATING_PROFIT
FROM ACCEL_DB.GOLD.FACT_GL
GROUP BY 1, 2, 3;

