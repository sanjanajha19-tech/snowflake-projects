/* =============================================================================
   05 LAKEHOUSE BLUEPRINT | 01_bronze.sql
   BRONZE = raw, as-landed copies of source tables with lineage columns.
   Built as Dynamic Tables over ACCEL_DB.DEMO (swap the FROM clause for
   ACCEL_DB.INGEST.RAW_* tables when using the ingestion framework).
   TARGET_LAG = DOWNSTREAM: bronze refreshes only when silver/gold need it.
   Run as: ACCEL_ADMIN.
============================================================================= */
USE ROLE ACCEL_ADMIN;
USE WAREHOUSE ACCEL_WH;
USE DATABASE ACCEL_DB;
CREATE SCHEMA IF NOT EXISTS BRONZE;
USE SCHEMA BRONZE;

CREATE OR REPLACE DYNAMIC TABLE BRZ_CUSTOMERS
  TARGET_LAG = DOWNSTREAM
  WAREHOUSE = ACCEL_WH
  COMMENT = 'Bronze copy of DEMO.CUSTOMERS'
AS
SELECT c.*, 'ACCEL_DB.DEMO.CUSTOMERS' AS _SOURCE_TABLE
FROM ACCEL_DB.DEMO.CUSTOMERS c;

