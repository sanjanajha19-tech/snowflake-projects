USE ROLE ACCEL_ADMIN;
USE WAREHOUSE ACCEL_WH;
USE DATABASE ACCEL_DB;
CREATE SCHEMA IF NOT EXISTS GOLD;
USE SCHEMA GOLD;

-- 1. Row-count reconciliation: DEMO -> BRONZE -> SILVER -> GOLD
SELECT 'CUSTOMERS' AS ENTITY,
       (SELECT COUNT(*) FROM ACCEL_DB.DEMO.CUSTOMERS)        AS SOURCE_ROWS,
       (SELECT COUNT(*) FROM ACCEL_DB.BRONZE.BRZ_CUSTOMERS)  AS BRONZE_ROWS,
       (SELECT COUNT(*) FROM ACCEL_DB.SILVER.SLV_CUSTOMERS)  AS SILVER_ROWS,
       (SELECT COUNT(*) FROM ACCEL_DB.GOLD.DIM_CUSTOMER)     AS GOLD_ROWS
UNION ALL
SELECT 'ORDER_LINES',
       (SELECT COUNT(*) FROM ACCEL_DB.DEMO.ORDER_LINES),
       (SELECT COUNT(*) FROM ACCEL_DB.BRONZE.BRZ_ORDER_LINES),
       (SELECT COUNT(*) FROM ACCEL_DB.SILVER.SLV_ORDER_LINES),
       (SELECT COUNT(*) FROM ACCEL_DB.GOLD.FACT_SALES)
UNION ALL
SELECT 'INVENTORY_SNAPSHOTS',
       (SELECT COUNT(*) FROM ACCEL_DB.DEMO.INVENTORY_SNAPSHOTS),
       (SELECT COUNT(*) FROM ACCEL_DB.BRONZE.BRZ_INVENTORY_SNAPSHOTS),
       (SELECT COUNT(*) FROM ACCEL_DB.SILVER.SLV_INVENTORY_SNAPSHOTS),
       (SELECT COUNT(*) FROM ACCEL_DB.GOLD.FACT_INVENTORY)
UNION ALL
SELECT 'GL_JOURNAL',
       (SELECT COUNT(*) FROM ACCEL_DB.DEMO.GL_JOURNAL),
       (SELECT COUNT(*) FROM ACCEL_DB.BRONZE.BRZ_GL_JOURNAL),
       (SELECT COUNT(*) FROM ACCEL_DB.SILVER.SLV_GL_JOURNAL),
       (SELECT COUNT(*) FROM ACCEL_DB.GOLD.FACT_GL);

-- 2. Amount reconciliation: NET_AMOUNT in source vs gold fact
SELECT (SELECT SUM(NET_AMOUNT) FROM ACCEL_DB.DEMO.ORDER_LINES) AS SOURCE_NET,
       (SELECT SUM(NET_AMOUNT) FROM ACCEL_DB.GOLD.FACT_SALES)  AS GOLD_NET;

-- 3. Referential integrity: fact rows without a matching dimension (expect 0)
SELECT 'FACT_SALES->DIM_CUSTOMER' AS CHECK_NAME, COUNT(*) AS ORPHANS
FROM ACCEL_DB.GOLD.FACT_SALES f LEFT JOIN ACCEL_DB.GOLD.DIM_CUSTOMER d ON d.CUSTOMER_SK = f.CUSTOMER_SK
WHERE d.CUSTOMER_SK IS NULL
UNION ALL
SELECT 'FACT_SALES->DIM_PRODUCT', COUNT(*)
FROM ACCEL_DB.GOLD.FACT_SALES f LEFT JOIN ACCEL_DB.GOLD.DIM_PRODUCT d ON d.PRODUCT_SK = f.PRODUCT_SK
WHERE d.PRODUCT_SK IS NULL
UNION ALL
SELECT 'FACT_SALES->DIM_DATE', COUNT(*)
FROM ACCEL_DB.GOLD.FACT_SALES f LEFT JOIN ACCEL_DB.GOLD.DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
WHERE d.DATE_KEY IS NULL;

-- 4. Dynamic table state and refresh history
SHOW DYNAMIC TABLES IN DATABASE ACCEL_DB;
SELECT "name", "schema_name", "target_lag", "refresh_mode", "scheduling_state", "data_timestamp"
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
ORDER BY "schema_name", "name";

SELECT NAME, SCHEMA_NAME, STATE, REFRESH_ACTION, REFRESH_TRIGGER,
       REFRESH_START_TIME, REFRESH_END_TIME, STATE_MESSAGE
FROM TABLE(ACCEL_DB.INFORMATION_SCHEMA.DYNAMIC_TABLE_REFRESH_HISTORY())
ORDER BY REFRESH_START_TIME DESC
LIMIT 50;

