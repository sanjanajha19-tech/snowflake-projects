-- USE ROLE ACCEL_ADMIN;

SELECT * FROM V_WAREHOUSE_GUARDRAILS
WHERE FLAG_AUTO_SUSPEND_DISABLED OR FLAG_AUTO_SUSPEND_GT_300 OR FLAG_NO_RESOURCE_MONITOR
   OR FLAG_AUTO_RESUME_OFF OR FLAG_HIGH_MAX_CLUSTERS
ORDER BY CREDITS_IDLE_30D DESC NULLS LAST;

-- Resource monitors defined in the account (quota and usage)
SELECT NAME, CREDIT_QUOTA, USED_CREDITS, REMAINING_CREDITS, LEVEL, WAREHOUSES,
       NOTIFY, SUSPEND, SUSPEND_IMMEDIATE
FROM SNOWFLAKE.ACCOUNT_USAGE.RESOURCE_MONITORS;

GRANT SELECT ON VIEW V_WAREHOUSE_GUARDRAILS TO ROLE ACCEL_ANALYST;
