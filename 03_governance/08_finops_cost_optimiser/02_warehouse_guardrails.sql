/* =============================================================================
   08 FINOPS COST OPTIMIZER | 02_warehouse_guardrails.sql
   ACCOUNT_USAGE has no warehouse-settings view, so SNAPSHOT_WAREHOUSES() stores
   SHOW WAREHOUSES output in WAREHOUSE_CONFIG. V_WAREHOUSE_GUARDRAILS flags
   AUTO_SUSPEND > 300 s / disabled, no resource monitor, auto-resume off,
   multi-cluster on STANDARD with high max clusters.
   SHOW WAREHOUSES only lists warehouses the role can see: for an account-wide
   picture run the CALL as ACCOUNTADMIN (commented below) or grant MONITOR on
   the warehouses to ACCEL_ADMIN.
   Run as: ACCEL_ADMIN.
============================================================================= */
USE ROLE ACCEL_ADMIN;
USE WAREHOUSE ACCEL_WH;
USE DATABASE ACCEL_DB;
CREATE SCHEMA IF NOT EXISTS FINOPS;
USE SCHEMA FINOPS;

CREATE TABLE IF NOT EXISTS WAREHOUSE_CONFIG (
  SNAPSHOT_TS        TIMESTAMP_LTZ,
  WAREHOUSE_NAME     VARCHAR,
  STATE              VARCHAR,
  WAREHOUSE_TYPE     VARCHAR,
  WAREHOUSE_SIZE     VARCHAR,
  MIN_CLUSTER_COUNT  NUMBER,
  MAX_CLUSTER_COUNT  NUMBER,
  SCALING_POLICY     VARCHAR,
  AUTO_SUSPEND       NUMBER,
  AUTO_RESUME        VARCHAR,
  RESOURCE_MONITOR   VARCHAR,
  OWNER              VARCHAR,
  COMMENT            VARCHAR
);

CREATE OR REPLACE PROCEDURE SNAPSHOT_WAREHOUSES()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
  n INTEGER;
BEGIN
  SHOW WAREHOUSES;
  CREATE OR REPLACE TEMPORARY TABLE ACCEL_DB.FINOPS.WH_SHOW_TMP AS
    SELECT * FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));
  DELETE FROM ACCEL_DB.FINOPS.WAREHOUSE_CONFIG;
  INSERT INTO ACCEL_DB.FINOPS.WAREHOUSE_CONFIG
  SELECT CURRENT_TIMESTAMP(), "name", "state", "type", "size",
         TRY_TO_NUMBER("min_cluster_count"::VARCHAR), TRY_TO_NUMBER("max_cluster_count"::VARCHAR),
         "scaling_policy", TRY_TO_NUMBER("auto_suspend"::VARCHAR), "auto_resume"::VARCHAR,
         NULLIF("resource_monitor", 'null'), "owner", "comment"
  FROM ACCEL_DB.FINOPS.WH_SHOW_TMP;
  n := SQLROWCOUNT;
  DROP TABLE IF EXISTS ACCEL_DB.FINOPS.WH_SHOW_TMP;
  RETURN n || ' warehouses captured';
END;
$$;

CREATE OR REPLACE VIEW V_WAREHOUSE_GUARDRAILS AS
SELECT c.WAREHOUSE_NAME, c.WAREHOUSE_SIZE, c.WAREHOUSE_TYPE, c.AUTO_SUSPEND, c.AUTO_RESUME,
       c.MIN_CLUSTER_COUNT, c.MAX_CLUSTER_COUNT, c.SCALING_POLICY, c.RESOURCE_MONITOR,
       (c.AUTO_SUSPEND IS NULL OR c.AUTO_SUSPEND = 0)       AS FLAG_AUTO_SUSPEND_DISABLED,
       (c.AUTO_SUSPEND > 300)                               AS FLAG_AUTO_SUSPEND_GT_300,
       (c.RESOURCE_MONITOR IS NULL)                         AS FLAG_NO_RESOURCE_MONITOR,
       (UPPER(c.AUTO_RESUME) = 'FALSE')                     AS FLAG_AUTO_RESUME_OFF,
       (c.MAX_CLUSTER_COUNT > 3)                            AS FLAG_HIGH_MAX_CLUSTERS,
       i.CREDITS_COMPUTE_30D,
       i.CREDITS_IDLE_30D,
       i.IDLE_PCT,
       c.SNAPSHOT_TS
FROM WAREHOUSE_CONFIG c
LEFT JOIN V_IDLE_WAREHOUSES i ON i.WAREHOUSE_NAME = c.WAREHOUSE_NAME;

CALL SNAPSHOT_WAREHOUSES();

-- Account-wide snapshot (ACCOUNTADMIN sees every warehouse):
