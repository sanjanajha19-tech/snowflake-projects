/* =============================================================================
   07 GOVERNANCE KIT | 01_role_hierarchy.sql
   Functional roles (who you are) + access roles (what you can touch) pattern:
     users -> FR_* account roles -> AR_* database roles in ACCEL_DB -> object privileges
   Also grants ACCEL_ADMIN the account-level governance privileges used by this kit.
============================================================================= */

-- ---------------------------------------------------------------------------
-- 1. ACCOUNTADMIN: account-level governance privileges for ACCEL_ADMIN
--    (APPLY TAG / MASKING / ROW ACCESS and DMF execution are account privileges)
-- ---------------------------------------------------------------------------
USE ROLE ACCOUNTADMIN;
GRANT APPLY TAG ON ACCOUNT TO ROLE ACCEL_ADMIN;
GRANT APPLY MASKING POLICY ON ACCOUNT TO ROLE ACCEL_ADMIN;
GRANT APPLY ROW ACCESS POLICY ON ACCOUNT TO ROLE ACCEL_ADMIN;
GRANT EXECUTE DATA METRIC FUNCTION ON ACCOUNT TO ROLE ACCEL_ADMIN;
GRANT APPLICATION ROLE SNOWFLAKE.DATA_QUALITY_MONITORING_VIEWER TO ROLE ACCEL_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.CLASSIFICATION_ADMIN TO ROLE ACCEL_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.DATA_METRIC_USER TO ROLE ACCEL_ADMIN;

-- ---------------------------------------------------------------------------
-- 2. SECURITYADMIN: functional roles (account roles) and hierarchy
-- ---------------------------------------------------------------------------
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS FR_SALES_ANALYST   COMMENT = 'Functional: sales & customer analytics';
CREATE ROLE IF NOT EXISTS FR_FINANCE_ANALYST COMMENT = 'Functional: finance / GL analytics';
CREATE ROLE IF NOT EXISTS FR_HR_ANALYST      COMMENT = 'Functional: people analytics';
CREATE ROLE IF NOT EXISTS FR_DATA_STEWARD    COMMENT = 'Functional: data governance stewardship';

-- Functional roles roll up to SYSADMIN (no orphan roles)
GRANT ROLE FR_SALES_ANALYST   TO ROLE SYSADMIN;
GRANT ROLE FR_FINANCE_ANALYST TO ROLE SYSADMIN;
GRANT ROLE FR_HR_ANALYST      TO ROLE SYSADMIN;
GRANT ROLE FR_DATA_STEWARD    TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE ACCEL_WH TO ROLE FR_SALES_ANALYST;
GRANT USAGE ON WAREHOUSE ACCEL_WH TO ROLE FR_FINANCE_ANALYST;
GRANT USAGE ON WAREHOUSE ACCEL_WH TO ROLE FR_HR_ANALYST;
GRANT USAGE ON WAREHOUSE ACCEL_WH TO ROLE FR_DATA_STEWARD;

-- ---------------------------------------------------------------------------
-- 3. ACCEL_ADMIN: access roles as DATABASE ROLES in ACCEL_DB + object privileges
-- ---------------------------------------------------------------------------
USE ROLE ACCEL_ADMIN;
USE WAREHOUSE ACCEL_WH;
USE DATABASE ACCEL_DB;
CREATE SCHEMA IF NOT EXISTS GOVERNANCE;
USE SCHEMA GOVERNANCE;

CREATE DATABASE ROLE IF NOT EXISTS ACCEL_DB.AR_SALES_READ      COMMENT = 'Read customers, products, orders';
CREATE DATABASE ROLE IF NOT EXISTS ACCEL_DB.AR_FINANCE_READ    COMMENT = 'Read GL journal';
CREATE DATABASE ROLE IF NOT EXISTS ACCEL_DB.AR_HR_READ         COMMENT = 'Read employees';
CREATE DATABASE ROLE IF NOT EXISTS ACCEL_DB.AR_SUPPLY_READ     COMMENT = 'Read suppliers, plants, POs, inventory';
CREATE DATABASE ROLE IF NOT EXISTS ACCEL_DB.AR_GOVERNANCE_READ COMMENT = 'Read governance reports';

GRANT USAGE ON SCHEMA ACCEL_DB.DEMO TO DATABASE ROLE ACCEL_DB.AR_SALES_READ;
GRANT USAGE ON SCHEMA ACCEL_DB.DEMO TO DATABASE ROLE ACCEL_DB.AR_FINANCE_READ;
GRANT USAGE ON SCHEMA ACCEL_DB.DEMO TO DATABASE ROLE ACCEL_DB.AR_HR_READ;
GRANT USAGE ON SCHEMA ACCEL_DB.DEMO TO DATABASE ROLE ACCEL_DB.AR_SUPPLY_READ;
GRANT USAGE ON SCHEMA ACCEL_DB.GOVERNANCE TO DATABASE ROLE ACCEL_DB.AR_GOVERNANCE_READ;
GRANT USAGE ON SCHEMA ACCEL_DB.GOVERNANCE TO DATABASE ROLE ACCEL_DB.AR_SALES_READ;   -- secure views live here

GRANT SELECT ON TABLE ACCEL_DB.DEMO.CUSTOMERS           TO DATABASE ROLE ACCEL_DB.AR_SALES_READ;
GRANT SELECT ON TABLE ACCEL_DB.DEMO.PRODUCTS            TO DATABASE ROLE ACCEL_DB.AR_SALES_READ;
GRANT SELECT ON TABLE ACCEL_DB.DEMO.ORDERS              TO DATABASE ROLE ACCEL_DB.AR_SALES_READ;
GRANT SELECT ON TABLE ACCEL_DB.DEMO.ORDER_LINES         TO DATABASE ROLE ACCEL_DB.AR_SALES_READ;
GRANT SELECT ON TABLE ACCEL_DB.DEMO.SUPPORT_TICKETS     TO DATABASE ROLE ACCEL_DB.AR_SALES_READ;
GRANT SELECT ON TABLE ACCEL_DB.DEMO.GL_JOURNAL          TO DATABASE ROLE ACCEL_DB.AR_FINANCE_READ;
GRANT SELECT ON TABLE ACCEL_DB.DEMO.EMPLOYEES           TO DATABASE ROLE ACCEL_DB.AR_HR_READ;
GRANT SELECT ON TABLE ACCEL_DB.DEMO.SUPPLIERS           TO DATABASE ROLE ACCEL_DB.AR_SUPPLY_READ;
GRANT SELECT ON TABLE ACCEL_DB.DEMO.PLANTS              TO DATABASE ROLE ACCEL_DB.AR_SUPPLY_READ;
GRANT SELECT ON TABLE ACCEL_DB.DEMO.PURCHASE_ORDERS     TO DATABASE ROLE ACCEL_DB.AR_SUPPLY_READ;
GRANT SELECT ON TABLE ACCEL_DB.DEMO.INVENTORY_SNAPSHOTS TO DATABASE ROLE ACCEL_DB.AR_SUPPLY_READ;

-- Access roles -> functional roles (database role owner can grant them)
GRANT DATABASE ROLE ACCEL_DB.AR_SALES_READ      TO ROLE FR_SALES_ANALYST;
GRANT DATABASE ROLE ACCEL_DB.AR_SUPPLY_READ     TO ROLE FR_SALES_ANALYST;
GRANT DATABASE ROLE ACCEL_DB.AR_FINANCE_READ    TO ROLE FR_FINANCE_ANALYST;
GRANT DATABASE ROLE ACCEL_DB.AR_SALES_READ      TO ROLE FR_FINANCE_ANALYST;
GRANT DATABASE ROLE ACCEL_DB.AR_HR_READ         TO ROLE FR_HR_ANALYST;
GRANT DATABASE ROLE ACCEL_DB.AR_GOVERNANCE_READ TO ROLE FR_DATA_STEWARD;
GRANT DATABASE ROLE ACCEL_DB.AR_SALES_READ      TO ROLE FR_DATA_STEWARD;
GRANT DATABASE ROLE ACCEL_DB.AR_HR_READ         TO ROLE FR_DATA_STEWARD;
GRANT DATABASE ROLE ACCEL_DB.AR_FINANCE_READ    TO ROLE FR_DATA_STEWARD;
GRANT DATABASE ROLE ACCEL_DB.AR_SUPPLY_READ     TO ROLE FR_DATA_STEWARD;
-- Existing accelerator analyst role gets sales + supply read through the same access roles
GRANT DATABASE ROLE ACCEL_DB.AR_SALES_READ      TO ROLE ACCEL_ANALYST;

-- Database usage for the functional roles (explicit, so the role can USE DATABASE)
GRANT USAGE ON DATABASE ACCEL_DB TO ROLE FR_SALES_ANALYST;
GRANT USAGE ON DATABASE ACCEL_DB TO ROLE FR_FINANCE_ANALYST;
GRANT USAGE ON DATABASE ACCEL_DB TO ROLE FR_HR_ANALYST;
GRANT USAGE ON DATABASE ACCEL_DB TO ROLE FR_DATA_STEWARD;

-- Inventory of the model
SHOW DATABASE ROLES IN DATABASE ACCEL_DB;
SHOW GRANTS TO ROLE FR_SALES_ANALYST;
