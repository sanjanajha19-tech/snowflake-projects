/* =============================================================================
   07 GOVERNANCE KIT | 07_governance_coverage.sql
   Governance coverage for every table in the schemas listed in COVERAGE_SCOPE:
   object tags (DOMAIN / DATA_OWNER / DATA_CLASSIFICATION), PII columns,
   PII columns protected by masking, classifier-detected columns not yet tagged,
   row access policy, attached DMFs and a 0-100 coverage score.
   - REFRESH_GOVERNANCE_COVERAGE() snapshots real-time INFORMATION_SCHEMA table
     functions (no ACCOUNT_USAGE latency) into GOV_* tables.
   - V_GOVERNANCE_COVERAGE = one row per table; V_GOVERNANCE_GAPS = to-do list.
   - V_GOVERNANCE_COVERAGE_ACCOUNT = account-wide view over ACCOUNT_USAGE (~2 h lag).
   Run as: ACCEL_ADMIN.
============================================================================= */
USE ROLE ACCEL_ADMIN;
USE WAREHOUSE ACCEL_WH;
USE DATABASE ACCEL_DB;
CREATE SCHEMA IF NOT EXISTS GOVERNANCE;
USE SCHEMA GOVERNANCE;

-- Schemas to assess (EDIT ME: add BRONZE, SILVER, GOLD, ... as you onboard them)
CREATE TABLE IF NOT EXISTS COVERAGE_SCOPE (DATABASE_NAME VARCHAR, SCHEMA_NAME VARCHAR);
MERGE INTO COVERAGE_SCOPE t
USING (SELECT 'ACCEL_DB' AS DATABASE_NAME, 'DEMO' AS SCHEMA_NAME) s
ON t.DATABASE_NAME = s.DATABASE_NAME AND t.SCHEMA_NAME = s.SCHEMA_NAME
WHEN NOT MATCHED THEN INSERT VALUES (s.DATABASE_NAME, s.SCHEMA_NAME);

CREATE TABLE IF NOT EXISTS GOV_TABLES        (SNAPSHOT_TS TIMESTAMP_LTZ, TABLE_FQN VARCHAR, TABLE_NAME VARCHAR, COLUMN_COUNT NUMBER, ROW_COUNT NUMBER);
CREATE TABLE IF NOT EXISTS GOV_TABLE_TAGS    (SNAPSHOT_TS TIMESTAMP_LTZ, TABLE_FQN VARCHAR, TAG_DATABASE VARCHAR, TAG_SCHEMA VARCHAR, TAG_NAME VARCHAR, TAG_VALUE VARCHAR, LEVEL VARCHAR);
CREATE TABLE IF NOT EXISTS GOV_COLUMN_TAGS   (SNAPSHOT_TS TIMESTAMP_LTZ, TABLE_FQN VARCHAR, COLUMN_NAME VARCHAR, TAG_DATABASE VARCHAR, TAG_SCHEMA VARCHAR, TAG_NAME VARCHAR, TAG_VALUE VARCHAR, LEVEL VARCHAR);
CREATE TABLE IF NOT EXISTS GOV_POLICIES      (SNAPSHOT_TS TIMESTAMP_LTZ, TABLE_FQN VARCHAR, COLUMN_NAME VARCHAR, POLICY_NAME VARCHAR, POLICY_KIND VARCHAR, TAG_NAME VARCHAR, POLICY_STATUS VARCHAR);
CREATE TABLE IF NOT EXISTS GOV_DMFS          (SNAPSHOT_TS TIMESTAMP_LTZ, TABLE_FQN VARCHAR, METRIC_NAME VARCHAR, SCHEDULE_STATUS VARCHAR);

CREATE OR REPLACE PROCEDURE REFRESH_GOVERNANCE_COVERAGE()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
  n INTEGER DEFAULT 0;
  fqn VARCHAR;
  c CURSOR FOR
    SELECT t.TABLE_CATALOG, t.TABLE_SCHEMA, t.TABLE_NAME, t.ROW_COUNT
    FROM ACCEL_DB.INFORMATION_SCHEMA.TABLES t
    JOIN ACCEL_DB.GOVERNANCE.COVERAGE_SCOPE s
      ON s.DATABASE_NAME = t.TABLE_CATALOG AND s.SCHEMA_NAME = t.TABLE_SCHEMA
    WHERE t.TABLE_TYPE = 'BASE TABLE';
BEGIN
  DELETE FROM ACCEL_DB.GOVERNANCE.GOV_TABLES;
  DELETE FROM ACCEL_DB.GOVERNANCE.GOV_TABLE_TAGS;
  DELETE FROM ACCEL_DB.GOVERNANCE.GOV_COLUMN_TAGS;
  DELETE FROM ACCEL_DB.GOVERNANCE.GOV_POLICIES;
  DELETE FROM ACCEL_DB.GOVERNANCE.GOV_DMFS;

  FOR r IN c DO
    fqn := r.TABLE_CATALOG || '.' || r.TABLE_SCHEMA || '.' || r.TABLE_NAME;

    EXECUTE IMMEDIATE 'INSERT INTO ACCEL_DB.GOVERNANCE.GOV_TABLES
      SELECT CURRENT_TIMESTAMP(), ''' || fqn || ''', ''' || r.TABLE_NAME || ''', COUNT(*), ' || COALESCE(r.ROW_COUNT, 0) || '
      FROM ACCEL_DB.INFORMATION_SCHEMA.COLUMNS
      WHERE TABLE_SCHEMA = ''' || r.TABLE_SCHEMA || ''' AND TABLE_NAME = ''' || r.TABLE_NAME || '''';

    EXECUTE IMMEDIATE 'INSERT INTO ACCEL_DB.GOVERNANCE.GOV_TABLE_TAGS
      SELECT CURRENT_TIMESTAMP(), ''' || fqn || ''', TAG_DATABASE, TAG_SCHEMA, TAG_NAME, TAG_VALUE, LEVEL
      FROM TABLE(ACCEL_DB.INFORMATION_SCHEMA.TAG_REFERENCES(''' || fqn || ''', ''table''))';

    EXECUTE IMMEDIATE 'INSERT INTO ACCEL_DB.GOVERNANCE.GOV_COLUMN_TAGS
      SELECT CURRENT_TIMESTAMP(), ''' || fqn || ''', COLUMN_NAME, TAG_DATABASE, TAG_SCHEMA, TAG_NAME, TAG_VALUE, LEVEL
      FROM TABLE(ACCEL_DB.INFORMATION_SCHEMA.TAG_REFERENCES_ALL_COLUMNS(''' || fqn || ''', ''table''))
      WHERE LEVEL = ''COLUMN''';

    EXECUTE IMMEDIATE 'INSERT INTO ACCEL_DB.GOVERNANCE.GOV_POLICIES
      SELECT CURRENT_TIMESTAMP(), ''' || fqn || ''', REF_COLUMN_NAME, POLICY_NAME, POLICY_KIND, TAG_NAME, POLICY_STATUS
      FROM TABLE(ACCEL_DB.INFORMATION_SCHEMA.POLICY_REFERENCES(REF_ENTITY_NAME => ''' || fqn || ''', REF_ENTITY_DOMAIN => ''table''))';

    EXECUTE IMMEDIATE 'INSERT INTO ACCEL_DB.GOVERNANCE.GOV_DMFS
      SELECT CURRENT_TIMESTAMP(), ''' || fqn || ''', METRIC_DATABASE_NAME || ''.'' || METRIC_SCHEMA_NAME || ''.'' || METRIC_NAME, SCHEDULE_STATUS
      FROM TABLE(ACCEL_DB.INFORMATION_SCHEMA.DATA_METRIC_FUNCTION_REFERENCES(REF_ENTITY_NAME => ''' || fqn || ''', REF_ENTITY_DOMAIN => ''TABLE''))';

    n := n + 1;
  END FOR;
  RETURN 'Coverage snapshot refreshed for ' || n || ' tables';
END;
$$;

-- One row per table
CREATE OR REPLACE VIEW V_GOVERNANCE_COVERAGE AS
WITH obj AS (
  SELECT TABLE_FQN,
         MAX(IFF(TAG_DATABASE = 'ACCEL_DB' AND TAG_SCHEMA = 'GOVERNANCE' AND TAG_NAME = 'DOMAIN', TAG_VALUE, NULL))              AS DOMAIN,
         MAX(IFF(TAG_DATABASE = 'ACCEL_DB' AND TAG_SCHEMA = 'GOVERNANCE' AND TAG_NAME = 'DATA_OWNER', TAG_VALUE, NULL))          AS DATA_OWNER,
         MAX(IFF(TAG_DATABASE = 'ACCEL_DB' AND TAG_SCHEMA = 'GOVERNANCE' AND TAG_NAME = 'DATA_CLASSIFICATION', TAG_VALUE, NULL)) AS DATA_CLASSIFICATION
  FROM GOV_TABLE_TAGS
  GROUP BY TABLE_FQN
),
pii AS (
  SELECT TABLE_FQN, COLUMN_NAME
  FROM GOV_COLUMN_TAGS
  WHERE TAG_DATABASE = 'ACCEL_DB' AND TAG_SCHEMA = 'GOVERNANCE' AND TAG_NAME = 'PII_TYPE'
  GROUP BY TABLE_FQN, COLUMN_NAME
),
classified AS (   -- columns the Snowflake classifier flagged (system tag)
  SELECT TABLE_FQN, COLUMN_NAME
  FROM GOV_COLUMN_TAGS
  WHERE TAG_DATABASE = 'SNOWFLAKE' AND TAG_SCHEMA = 'CORE' AND TAG_NAME = 'SEMANTIC_CATEGORY'
  GROUP BY TABLE_FQN, COLUMN_NAME
),
masked AS (
  SELECT TABLE_FQN, COLUMN_NAME
  FROM GOV_POLICIES WHERE POLICY_KIND = 'MASKING_POLICY' AND COLUMN_NAME IS NOT NULL
  GROUP BY TABLE_FQN, COLUMN_NAME
),
pii_stats AS (
  SELECT p.TABLE_FQN, COUNT(*) AS PII_COLUMNS, COUNT(m.COLUMN_NAME) AS PII_COLUMNS_MASKED
  FROM pii p
  LEFT JOIN masked m ON m.TABLE_FQN = p.TABLE_FQN AND m.COLUMN_NAME = p.COLUMN_NAME
  GROUP BY p.TABLE_FQN
),
class_stats AS (
  SELECT c.TABLE_FQN, COUNT_IF(p.COLUMN_NAME IS NULL) AS CLASSIFIED_NOT_TAGGED
  FROM classified c
  LEFT JOIN pii p ON p.TABLE_FQN = c.TABLE_FQN AND p.COLUMN_NAME = c.COLUMN_NAME
  GROUP BY c.TABLE_FQN
),
rap AS (
  SELECT TABLE_FQN, LISTAGG(DISTINCT POLICY_NAME, ', ') AS ROW_ACCESS_POLICY
  FROM GOV_POLICIES WHERE POLICY_KIND = 'ROW_ACCESS_POLICY' GROUP BY TABLE_FQN
),
dmf AS (
  SELECT TABLE_FQN, COUNT(*) AS DMF_COUNT FROM GOV_DMFS GROUP BY TABLE_FQN
),
base AS (
  SELECT t.SNAPSHOT_TS, t.TABLE_FQN, t.TABLE_NAME, t.COLUMN_COUNT, t.ROW_COUNT,
         o.DOMAIN, o.DATA_OWNER, o.DATA_CLASSIFICATION,
         COALESCE(ps.PII_COLUMNS, 0)           AS PII_COLUMNS,
         COALESCE(ps.PII_COLUMNS_MASKED, 0)    AS PII_COLUMNS_MASKED,
         COALESCE(cs.CLASSIFIED_NOT_TAGGED, 0) AS CLASSIFIED_NOT_TAGGED,
         r.ROW_ACCESS_POLICY,
         COALESCE(d.DMF_COUNT, 0)              AS DMF_COUNT
  FROM GOV_TABLES t
  LEFT JOIN obj o          ON o.TABLE_FQN = t.TABLE_FQN
  LEFT JOIN pii_stats ps   ON ps.TABLE_FQN = t.TABLE_FQN
  LEFT JOIN class_stats cs ON cs.TABLE_FQN = t.TABLE_FQN
  LEFT JOIN rap r          ON r.TABLE_FQN = t.TABLE_FQN
  LEFT JOIN dmf d          ON d.TABLE_FQN = t.TABLE_FQN
)
SELECT base.*,
       -- Score: 3 object tags (15 each) + PII masked (25) + no untagged sensitive columns (10) + DMFs (20)
       (IFF(DOMAIN IS NOT NULL, 15, 0) + IFF(DATA_OWNER IS NOT NULL, 15, 0) + IFF(DATA_CLASSIFICATION IS NOT NULL, 15, 0)
        + IFF(PII_COLUMNS = PII_COLUMNS_MASKED, 25, ROUND(25 * PII_COLUMNS_MASKED / NULLIF(PII_COLUMNS, 0)))
        + IFF(CLASSIFIED_NOT_TAGGED = 0, 10, 0)
        + IFF(DMF_COUNT > 0, 20, 0))                                                                      AS COVERAGE_SCORE
FROM base;

-- Actionable gaps
CREATE OR REPLACE VIEW V_GOVERNANCE_GAPS AS
SELECT TABLE_FQN, 'Missing DOMAIN tag' AS GAP, 'ALTER TABLE ' || TABLE_FQN || ' SET TAG ACCEL_DB.GOVERNANCE.DOMAIN = ''<value>'';' AS FIX
FROM V_GOVERNANCE_COVERAGE WHERE DOMAIN IS NULL
UNION ALL
SELECT TABLE_FQN, 'Missing DATA_OWNER tag', 'ALTER TABLE ' || TABLE_FQN || ' SET TAG ACCEL_DB.GOVERNANCE.DATA_OWNER = ''<value>'';'
FROM V_GOVERNANCE_COVERAGE WHERE DATA_OWNER IS NULL
UNION ALL
SELECT TABLE_FQN, 'Missing DATA_CLASSIFICATION tag', 'ALTER TABLE ' || TABLE_FQN || ' SET TAG ACCEL_DB.GOVERNANCE.DATA_CLASSIFICATION = ''<value>'';'
FROM V_GOVERNANCE_COVERAGE WHERE DATA_CLASSIFICATION IS NULL
UNION ALL
SELECT TABLE_FQN, 'PII columns without masking: ' || (PII_COLUMNS - PII_COLUMNS_MASKED), 'Check PII_TYPE tag value / data type matches a policy on the tag'
FROM V_GOVERNANCE_COVERAGE WHERE PII_COLUMNS > PII_COLUMNS_MASKED
UNION ALL
SELECT TABLE_FQN, 'Classifier-detected columns without PII_TYPE tag: ' || CLASSIFIED_NOT_TAGGED, 'Review 03_auto_classification.sql results and tag the columns'
FROM V_GOVERNANCE_COVERAGE WHERE CLASSIFIED_NOT_TAGGED > 0
UNION ALL
SELECT TABLE_FQN, 'No data metric functions', 'ALTER TABLE ' || TABLE_FQN || ' ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.ROW_COUNT ON ();'
FROM V_GOVERNANCE_COVERAGE WHERE DMF_COUNT = 0;

-- Account-wide coverage from ACCOUNT_USAGE (up to ~2 h latency, all databases)
CREATE OR REPLACE VIEW V_GOVERNANCE_COVERAGE_ACCOUNT AS
WITH cols AS (
  SELECT TABLE_CATALOG, TABLE_SCHEMA, TABLE_NAME, COUNT(*) AS COLUMN_COUNT
  FROM SNOWFLAKE.ACCOUNT_USAGE.COLUMNS
  WHERE DELETED IS NULL
  GROUP BY 1, 2, 3
),
tagged AS (
  SELECT OBJECT_DATABASE, OBJECT_SCHEMA, OBJECT_NAME,
         COUNT(DISTINCT IFF(DOMAIN = 'COLUMN', COLUMN_NAME, NULL)) AS TAGGED_COLUMNS,
         COUNT(DISTINCT IFF(DOMAIN = 'TABLE', TAG_NAME, NULL))     AS TABLE_TAGS
  FROM SNOWFLAKE.ACCOUNT_USAGE.TAG_REFERENCES
  WHERE OBJECT_DELETED IS NULL
  GROUP BY 1, 2, 3
),
pol AS (
  SELECT REF_DATABASE_NAME, REF_SCHEMA_NAME, REF_ENTITY_NAME,
         COUNT(DISTINCT IFF(POLICY_KIND = 'MASKING_POLICY', REF_COLUMN_NAME, NULL)) AS MASKED_COLUMNS,
         MAX(IFF(POLICY_KIND = 'ROW_ACCESS_POLICY', 1, 0))                          AS HAS_ROW_ACCESS_POLICY
  FROM SNOWFLAKE.ACCOUNT_USAGE.POLICY_REFERENCES
  GROUP BY 1, 2, 3
)
SELECT c.TABLE_CATALOG AS DATABASE_NAME, c.TABLE_SCHEMA AS SCHEMA_NAME, c.TABLE_NAME, c.COLUMN_COUNT,
       COALESCE(t.TABLE_TAGS, 0)            AS TABLE_TAGS,
       COALESCE(t.TAGGED_COLUMNS, 0)        AS TAGGED_COLUMNS,
       COALESCE(p.MASKED_COLUMNS, 0)        AS MASKED_COLUMNS,
       COALESCE(p.HAS_ROW_ACCESS_POLICY, 0) AS HAS_ROW_ACCESS_POLICY
FROM cols c
LEFT JOIN tagged t ON t.OBJECT_DATABASE = c.TABLE_CATALOG AND t.OBJECT_SCHEMA = c.TABLE_SCHEMA AND t.OBJECT_NAME = c.TABLE_NAME
LEFT JOIN pol p    ON p.REF_DATABASE_NAME = c.TABLE_CATALOG AND p.REF_SCHEMA_NAME = c.TABLE_SCHEMA AND p.REF_ENTITY_NAME = c.TABLE_NAME
WHERE c.TABLE_CATALOG NOT IN ('SNOWFLAKE');

GRANT SELECT ON VIEW V_GOVERNANCE_COVERAGE TO DATABASE ROLE ACCEL_DB.AR_GOVERNANCE_READ;
GRANT SELECT ON VIEW V_GOVERNANCE_GAPS     TO DATABASE ROLE ACCEL_DB.AR_GOVERNANCE_READ;
GRANT SELECT ON ALL TABLES IN SCHEMA ACCEL_DB.GOVERNANCE TO DATABASE ROLE ACCEL_DB.AR_GOVERNANCE_READ;

CALL REFRESH_GOVERNANCE_COVERAGE();

SELECT TABLE_NAME, DOMAIN, DATA_OWNER, DATA_CLASSIFICATION, PII_COLUMNS, PII_COLUMNS_MASKED,
       CLASSIFIED_NOT_TAGGED, ROW_ACCESS_POLICY, DMF_COUNT, COVERAGE_SCORE
FROM V_GOVERNANCE_COVERAGE
ORDER BY COVERAGE_SCORE, TABLE_NAME;

SELECT * FROM V_GOVERNANCE_GAPS ORDER BY TABLE_FQN, GAP;

-- Optional: refresh the snapshot daily (created suspended)
CREATE OR REPLACE TASK TASK_REFRESH_GOVERNANCE_COVERAGE
  WAREHOUSE = ACCEL_WH
  SCHEDULE = 'USING CRON 0 6 * * * UTC'      -- EDIT ME
AS
  CALL ACCEL_DB.GOVERNANCE.REFRESH_GOVERNANCE_COVERAGE();
