/* =============================================================================
   07 GOVERNANCE KIT | 05_data_metric_functions.sql
   Data quality with Data Metric Functions (DMFs):
   - system DMFs: NULL_COUNT, DUPLICATE_COUNT, ROW_COUNT, FRESHNESS
   - custom DMFs: INVALID_EMAIL_COUNT, NEGATIVE_AMOUNT_COUNT
   Results land in SNOWFLAKE.LOCAL.DATA_QUALITY_MONITORING_RESULTS.
   DMFs run serverless on the table's DATA_METRIC_SCHEDULE.
   Run as: ACCEL_ADMIN (EXECUTE DATA METRIC FUNCTION granted in file 01).
============================================================================= */
USE ROLE ACCEL_ADMIN;
USE WAREHOUSE ACCEL_WH;
USE DATABASE ACCEL_DB;
CREATE SCHEMA IF NOT EXISTS GOVERNANCE;
USE SCHEMA GOVERNANCE;

-- ---------------------------------------------------------------------------
-- Custom DMFs
-- ---------------------------------------------------------------------------
CREATE OR REPLACE DATA METRIC FUNCTION INVALID_EMAIL_COUNT(ARG_T TABLE(ARG_C1 VARCHAR))
RETURNS NUMBER
COMMENT = 'Rows whose e-mail is NULL or not a valid address'
AS
$$
  SELECT COUNT_IF(ARG_C1 IS NULL OR NOT REGEXP_LIKE(ARG_C1, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+[.][A-Za-z]{2,}$'))
  FROM ARG_T
$$;

CREATE OR REPLACE DATA METRIC FUNCTION NEGATIVE_AMOUNT_COUNT(ARG_T TABLE(ARG_C1 NUMBER))
RETURNS NUMBER
COMMENT = 'Rows with a negative amount'
AS
$$
  SELECT COUNT_IF(ARG_C1 < 0) FROM ARG_T
$$;

-- ---------------------------------------------------------------------------
-- Schedules (EDIT ME: '60 MINUTE' is good for a demo; use a daily CRON in production,
-- e.g. 'USING CRON 0 6 * * * UTC', or 'TRIGGER_ON_CHANGES')
-- ---------------------------------------------------------------------------
ALTER TABLE ACCEL_DB.DEMO.CUSTOMERS   SET DATA_METRIC_SCHEDULE = '60 MINUTE';
ALTER TABLE ACCEL_DB.DEMO.ORDERS      SET DATA_METRIC_SCHEDULE = '60 MINUTE';
ALTER TABLE ACCEL_DB.DEMO.ORDER_LINES SET DATA_METRIC_SCHEDULE = '60 MINUTE';
ALTER TABLE ACCEL_DB.DEMO.GL_JOURNAL  SET DATA_METRIC_SCHEDULE = '60 MINUTE';

-- ---------------------------------------------------------------------------
-- Attach DMFs (SAFE_EXEC = skip if already attached, so the file can be rerun)
-- ---------------------------------------------------------------------------
CALL SAFE_EXEC('ALTER TABLE ACCEL_DB.DEMO.CUSTOMERS ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (EMAIL)');
CALL SAFE_EXEC('ALTER TABLE ACCEL_DB.DEMO.CUSTOMERS ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.DUPLICATE_COUNT ON (CUSTOMER_ID)');
CALL SAFE_EXEC('ALTER TABLE ACCEL_DB.DEMO.CUSTOMERS ADD DATA METRIC FUNCTION ACCEL_DB.GOVERNANCE.INVALID_EMAIL_COUNT ON (EMAIL)');
CALL SAFE_EXEC('ALTER TABLE ACCEL_DB.DEMO.ORDERS ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (CUSTOMER_ID)');
CALL SAFE_EXEC('ALTER TABLE ACCEL_DB.DEMO.ORDERS ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.DUPLICATE_COUNT ON (ORDER_ID)');
CALL SAFE_EXEC('ALTER TABLE ACCEL_DB.DEMO.ORDERS ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.ROW_COUNT ON ()');
CALL SAFE_EXEC('ALTER TABLE ACCEL_DB.DEMO.ORDERS ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.FRESHNESS ON ()');
CALL SAFE_EXEC('ALTER TABLE ACCEL_DB.DEMO.ORDER_LINES ADD DATA METRIC FUNCTION ACCEL_DB.GOVERNANCE.NEGATIVE_AMOUNT_COUNT ON (NET_AMOUNT)');
CALL SAFE_EXEC('ALTER TABLE ACCEL_DB.DEMO.GL_JOURNAL ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (APPROVED_BY)');
CALL SAFE_EXEC('ALTER TABLE ACCEL_DB.DEMO.GL_JOURNAL ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.FRESHNESS ON ()');

-- What is attached (real time)
SELECT METRIC_DATABASE_NAME, METRIC_SCHEMA_NAME, METRIC_NAME, REF_ENTITY_NAME, REF_ARGUMENTS, SCHEDULE, SCHEDULE_STATUS
FROM TABLE(ACCEL_DB.INFORMATION_SCHEMA.DATA_METRIC_FUNCTION_REFERENCES(
       REF_ENTITY_NAME => 'ACCEL_DB.DEMO.CUSTOMERS', REF_ENTITY_DOMAIN => 'TABLE'));

-- Immediate results without waiting for the schedule (ad-hoc DMF calls)
SELECT 'CUSTOMERS.EMAIL nulls'          AS CHECK_NAME, SNOWFLAKE.CORE.NULL_COUNT(SELECT EMAIL FROM ACCEL_DB.DEMO.CUSTOMERS) AS VALUE
UNION ALL
SELECT 'CUSTOMERS.CUSTOMER_ID duplicates', SNOWFLAKE.CORE.DUPLICATE_COUNT(SELECT CUSTOMER_ID FROM ACCEL_DB.DEMO.CUSTOMERS)
UNION ALL
SELECT 'CUSTOMERS.EMAIL invalid',        ACCEL_DB.GOVERNANCE.INVALID_EMAIL_COUNT(SELECT EMAIL FROM ACCEL_DB.DEMO.CUSTOMERS)
UNION ALL
SELECT 'ORDER_LINES.NET_AMOUNT negative', ACCEL_DB.GOVERNANCE.NEGATIVE_AMOUNT_COUNT(SELECT NET_AMOUNT FROM ACCEL_DB.DEMO.ORDER_LINES)
UNION ALL
SELECT 'GL_JOURNAL.APPROVED_BY nulls',   SNOWFLAKE.CORE.NULL_COUNT(SELECT APPROVED_BY FROM ACCEL_DB.DEMO.GL_JOURNAL);

