/* =============================================================================
   07 GOVERNANCE KIT | 04_apply_tags.sql
   Tags DEMO tables (object level) and sensitive columns (column level).
   SET TAG overwrites the value, so the file is rerunnable.
   Also creates SAFE_EXEC, a helper used by later files for statements that
   fail when re-run (attach DMF, attach policy to tag).
   Run as: ACCEL_ADMIN.
============================================================================= */
USE ROLE ACCEL_ADMIN;
USE WAREHOUSE ACCEL_WH;
USE DATABASE ACCEL_DB;
CREATE SCHEMA IF NOT EXISTS GOVERNANCE;
USE SCHEMA GOVERNANCE;

CREATE OR REPLACE PROCEDURE SAFE_EXEC(STMT VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
COMMENT = 'Runs a statement; returns SKIPPED instead of failing (for idempotent re-runs)'
AS
$$
BEGIN
  EXECUTE IMMEDIATE :STMT;
  RETURN 'OK: ' || STMT;
EXCEPTION
  WHEN OTHER THEN
    RETURN 'SKIPPED (' || SQLERRM || '): ' || STMT;
END;
$$;

