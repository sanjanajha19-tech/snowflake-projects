SELECT SCHEMA_NAME, TABLE_NAME, HEALTH, ROW_COUNT, MINUTES_SINCE_CHANGE, FRESHNESS_SLA_MINUTES, OPEN_MONITORS
FROM V_TABLE_HEALTH ORDER BY OPEN_INCIDENTS DESC, TABLE_NAME;
