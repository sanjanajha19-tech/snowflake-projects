/* =============================================================================
   17 DATA OBSERVABILITY | 02_snapshots_and_evaluation.sql
   TABLE_SNAPSHOTS     : history of row count, bytes, last change time and column
                         list per monitored table (ACCEL_DB.INFORMATION_SCHEMA:
                         real time, no ACCOUNT_USAGE lag).
   INCIDENTS           : one row per detected issue (OPEN | ACKNOWLEDGED | RESOLVED).
   TAKE_SNAPSHOT()     : writes one snapshot of every enabled monitored table.
   SET_INCIDENT_STATUS(id, status, note) : acknowledge / resolve from SQL or the app.
   EVALUATE_MONITORS() : snapshot, then compare with thresholds and with the
                         previous snapshot:
       MISSING_TABLE  configured table no longer exists              (state)
       FRESHNESS      not modified for longer than FRESHNESS_SLA       (state)
       VOLUME_MIN     row count below MIN_ROWS                        (state)
       VOLUME_CHANGE  row count moved > MAX_ROW_CHANGE_PCT since last  (event)
       SCHEMA_CHANGE  columns / data types changed since last          (event)
     State incidents are de-duplicated while open and auto-resolve when the
     condition clears. Event incidents are raised once and closed by a person.
   V_TABLE_HEALTH, V_INCIDENT_SUMMARY, V_DDL_ACTIVITY_7D (ACCOUNT_USAGE.TABLES/COLUMNS).
   TASK_OBS_EVALUATE   : hourly, created suspended.
   Run as: ACCEL_ADMIN. Prerequisite: 01_monitor_config.sql.
============================================================================= */
USE ROLE ACCEL_ADMIN;
USE WAREHOUSE ACCEL_WH;
USE DATABASE ACCEL_DB;
CREATE SCHEMA IF NOT EXISTS OBSERVABILITY;
USE SCHEMA OBSERVABILITY;

CREATE TABLE IF NOT EXISTS TABLE_SNAPSHOTS (
  SNAPSHOT_TS    TIMESTAMP_LTZ,
  SCHEMA_NAME    VARCHAR,
  TABLE_NAME     VARCHAR,
  TABLE_EXISTS   BOOLEAN,
  ROW_COUNT      NUMBER,
  BYTES          NUMBER,
  LAST_ALTERED   TIMESTAMP_LTZ,
  COLUMN_COUNT   NUMBER,
  COLUMN_LIST    VARCHAR,       -- "COL TYPE, COL TYPE, ..." in ordinal order
  SCHEMA_HASH    VARCHAR
);

CREATE SEQUENCE IF NOT EXISTS INCIDENT_SEQ;

CREATE TABLE IF NOT EXISTS INCIDENTS (
  INCIDENT_ID     NUMBER DEFAULT INCIDENT_SEQ.NEXTVAL,
  DETECTED_AT     TIMESTAMP_LTZ,
  LAST_SEEN_AT    TIMESTAMP_LTZ,
  SCHEMA_NAME     VARCHAR,
  TABLE_NAME      VARCHAR,
  MONITOR_TYPE    VARCHAR,
  SEVERITY        VARCHAR,
  OBSERVED_VALUE  VARCHAR,
  THRESHOLD       VARCHAR,
  MESSAGE         VARCHAR,
  STATUS          VARCHAR,        -- OPEN | ACKNOWLEDGED | RESOLVED
  NOTIFIED_AT     TIMESTAMP_LTZ,  -- set by NOTIFY_NEW_INCIDENTS (file 03)
  RESOLVED_AT     TIMESTAMP_LTZ,
  RESOLVED_BY     VARCHAR,
  RESOLUTION_NOTE VARCHAR
);

CREATE OR REPLACE PROCEDURE TAKE_SNAPSHOT()
RETURNS TIMESTAMP_LTZ
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
  ts TIMESTAMP_LTZ;
BEGIN
  ts := CURRENT_TIMESTAMP();
  INSERT INTO ACCEL_DB.OBSERVABILITY.TABLE_SNAPSHOTS
  SELECT :ts, m.SCHEMA_NAME, m.TABLE_NAME,
         (t.TABLE_NAME IS NOT NULL), t.ROW_COUNT, t.BYTES, t.LAST_ALTERED,
         c.COLUMN_COUNT, c.COLUMN_LIST, MD5(c.COLUMN_LIST)
  FROM ACCEL_DB.OBSERVABILITY.MONITOR_CONFIG m
  LEFT JOIN ACCEL_DB.INFORMATION_SCHEMA.TABLES t
         ON t.TABLE_SCHEMA = m.SCHEMA_NAME AND t.TABLE_NAME = m.TABLE_NAME
  LEFT JOIN (
         SELECT TABLE_SCHEMA, TABLE_NAME, COUNT(*) AS COLUMN_COUNT,
                LISTAGG(COLUMN_NAME || ' ' || DATA_TYPE, ', ') WITHIN GROUP (ORDER BY ORDINAL_POSITION) AS COLUMN_LIST
         FROM ACCEL_DB.INFORMATION_SCHEMA.COLUMNS
         GROUP BY TABLE_SCHEMA, TABLE_NAME
       ) c ON c.TABLE_SCHEMA = m.SCHEMA_NAME AND c.TABLE_NAME = m.TABLE_NAME
  WHERE m.ENABLED;
  RETURN ts;
END;
$$;

CREATE OR REPLACE PROCEDURE EVALUATE_MONITORS()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
  ts         TIMESTAMP_LTZ;
  n_new      INTEGER DEFAULT 0;
  n_resolved INTEGER DEFAULT 0;
  n_open     INTEGER DEFAULT 0;
BEGIN
  CALL ACCEL_DB.OBSERVABILITY.TAKE_SNAPSHOT();
  SELECT MAX(SNAPSHOT_TS) INTO :ts FROM ACCEL_DB.OBSERVABILITY.TABLE_SNAPSHOTS;

  CREATE OR REPLACE TEMPORARY TABLE ACCEL_DB.OBSERVABILITY.TMP_CANDIDATES AS
  WITH cur AS (
    SELECT * FROM ACCEL_DB.OBSERVABILITY.TABLE_SNAPSHOTS WHERE SNAPSHOT_TS = :ts
  ),
  prev AS (
    SELECT * FROM ACCEL_DB.OBSERVABILITY.TABLE_SNAPSHOTS
    WHERE SNAPSHOT_TS < :ts AND TABLE_EXISTS
    QUALIFY ROW_NUMBER() OVER (PARTITION BY SCHEMA_NAME, TABLE_NAME ORDER BY SNAPSHOT_TS DESC) = 1
  ),
  x AS (
    SELECT c.*, m.FRESHNESS_SLA_MINUTES, m.MIN_ROWS, m.MAX_ROW_CHANGE_PCT, m.CHECK_SCHEMA,
           COALESCE(m.SEVERITY, 'MEDIUM') AS CFG_SEVERITY,
           p.ROW_COUNT AS PREV_ROW_COUNT, p.SCHEMA_HASH AS PREV_SCHEMA_HASH, p.COLUMN_LIST AS PREV_COLUMN_LIST,
           p.SNAPSHOT_TS AS PREV_SNAPSHOT_TS
    FROM cur c
    JOIN ACCEL_DB.OBSERVABILITY.MONITOR_CONFIG m ON m.SCHEMA_NAME = c.SCHEMA_NAME AND m.TABLE_NAME = c.TABLE_NAME
    LEFT JOIN prev p ON p.SCHEMA_NAME = c.SCHEMA_NAME AND p.TABLE_NAME = c.TABLE_NAME
  )
  SELECT SCHEMA_NAME, TABLE_NAME, 'MISSING_TABLE' AS MONITOR_TYPE, 'CRITICAL' AS SEVERITY,
         'not found' AS OBSERVED_VALUE, 'table exists' AS THRESHOLD,
         'Monitored table ACCEL_DB.' || SCHEMA_NAME || '.' || TABLE_NAME || ' does not exist (dropped or renamed).' AS MESSAGE
  FROM x WHERE NOT TABLE_EXISTS
  UNION ALL
  SELECT SCHEMA_NAME, TABLE_NAME, 'FRESHNESS', CFG_SEVERITY,
         DATEDIFF('minute', LAST_ALTERED, :ts) || ' min', FRESHNESS_SLA_MINUTES || ' min',
         'Not modified since ' || TO_VARCHAR(LAST_ALTERED, 'YYYY-MM-DD HH24:MI') || ' ('
           || ROUND(DATEDIFF('minute', LAST_ALTERED, :ts) / 60, 1) || ' h); SLA is '
           || ROUND(FRESHNESS_SLA_MINUTES / 60, 1) || ' h.'
  FROM x WHERE TABLE_EXISTS AND FRESHNESS_SLA_MINUTES IS NOT NULL
           AND DATEDIFF('second', LAST_ALTERED, :ts) > FRESHNESS_SLA_MINUTES * 60
  UNION ALL
  SELECT SCHEMA_NAME, TABLE_NAME, 'VOLUME_MIN', CFG_SEVERITY,
         TO_VARCHAR(ROW_COUNT), '>= ' || MIN_ROWS,
         'Row count ' || ROW_COUNT || ' is below the minimum of ' || MIN_ROWS || '.'
  FROM x WHERE TABLE_EXISTS AND MIN_ROWS IS NOT NULL AND COALESCE(ROW_COUNT, 0) < MIN_ROWS
  UNION ALL
  SELECT SCHEMA_NAME, TABLE_NAME, 'VOLUME_CHANGE', CFG_SEVERITY,
         ROUND((ROW_COUNT - PREV_ROW_COUNT) * 100 / PREV_ROW_COUNT, 1) || ' %', '+/- ' || MAX_ROW_CHANGE_PCT || ' %',
         'Row count moved from ' || PREV_ROW_COUNT || ' to ' || ROW_COUNT || ' since '
           || TO_VARCHAR(PREV_SNAPSHOT_TS, 'YYYY-MM-DD HH24:MI') || '.'
  FROM x WHERE TABLE_EXISTS AND MAX_ROW_CHANGE_PCT IS NOT NULL AND PREV_ROW_COUNT > 0
           AND ABS(ROW_COUNT - PREV_ROW_COUNT) * 100 / PREV_ROW_COUNT > MAX_ROW_CHANGE_PCT
  UNION ALL
  SELECT SCHEMA_NAME, TABLE_NAME, 'SCHEMA_CHANGE', IFF(CFG_SEVERITY = 'CRITICAL', 'CRITICAL', 'HIGH'),
         COLUMN_COUNT || ' columns', 'no change',
         'Schema changed since ' || TO_VARCHAR(PREV_SNAPSHOT_TS, 'YYYY-MM-DD HH24:MI')
           || '. Added/changed: ' || COALESCE(NULLIF(ARRAY_TO_STRING(ARRAY_EXCEPT(SPLIT(COLUMN_LIST, ', '), SPLIT(PREV_COLUMN_LIST, ', ')), ', '), ''), 'none')
           || '. Removed/changed: ' || COALESCE(NULLIF(ARRAY_TO_STRING(ARRAY_EXCEPT(SPLIT(PREV_COLUMN_LIST, ', '), SPLIT(COLUMN_LIST, ', ')), ', '), ''), 'none')
           || '.'
  FROM x WHERE TABLE_EXISTS AND CHECK_SCHEMA AND PREV_SCHEMA_HASH IS NOT NULL AND SCHEMA_HASH <> PREV_SCHEMA_HASH;

  -- State incidents: update the open one, or open a new one
  MERGE INTO ACCEL_DB.OBSERVABILITY.INCIDENTS i
  USING (SELECT * FROM ACCEL_DB.OBSERVABILITY.TMP_CANDIDATES
         WHERE MONITOR_TYPE IN ('MISSING_TABLE', 'FRESHNESS', 'VOLUME_MIN')) c
  ON  i.SCHEMA_NAME = c.SCHEMA_NAME AND i.TABLE_NAME = c.TABLE_NAME
  AND i.MONITOR_TYPE = c.MONITOR_TYPE AND i.STATUS IN ('OPEN', 'ACKNOWLEDGED')
  WHEN MATCHED THEN UPDATE SET
       i.LAST_SEEN_AT = :ts, i.OBSERVED_VALUE = c.OBSERVED_VALUE, i.THRESHOLD = c.THRESHOLD, i.MESSAGE = c.MESSAGE
  WHEN NOT MATCHED THEN INSERT
       (DETECTED_AT, LAST_SEEN_AT, SCHEMA_NAME, TABLE_NAME, MONITOR_TYPE, SEVERITY, OBSERVED_VALUE, THRESHOLD, MESSAGE, STATUS)
       VALUES (:ts, :ts, c.SCHEMA_NAME, c.TABLE_NAME, c.MONITOR_TYPE, c.SEVERITY, c.OBSERVED_VALUE, c.THRESHOLD, c.MESSAGE, 'OPEN');

  -- Event incidents: always a new incident
  INSERT INTO ACCEL_DB.OBSERVABILITY.INCIDENTS
       (DETECTED_AT, LAST_SEEN_AT, SCHEMA_NAME, TABLE_NAME, MONITOR_TYPE, SEVERITY, OBSERVED_VALUE, THRESHOLD, MESSAGE, STATUS)
  SELECT :ts, :ts, SCHEMA_NAME, TABLE_NAME, MONITOR_TYPE, SEVERITY, OBSERVED_VALUE, THRESHOLD, MESSAGE, 'OPEN'
  FROM ACCEL_DB.OBSERVABILITY.TMP_CANDIDATES
  WHERE MONITOR_TYPE IN ('VOLUME_CHANGE', 'SCHEMA_CHANGE');

  SELECT COUNT(*) INTO :n_new FROM ACCEL_DB.OBSERVABILITY.INCIDENTS WHERE DETECTED_AT = :ts;

  -- Auto-resolve state incidents whose condition has cleared (only for tables checked in this run)
  UPDATE ACCEL_DB.OBSERVABILITY.INCIDENTS i
     SET STATUS = 'RESOLVED', RESOLVED_AT = :ts, RESOLVED_BY = 'AUTO', RESOLUTION_NOTE = 'Condition cleared'
   WHERE i.STATUS IN ('OPEN', 'ACKNOWLEDGED')
     AND i.MONITOR_TYPE IN ('MISSING_TABLE', 'FRESHNESS', 'VOLUME_MIN')
     AND EXISTS (SELECT 1 FROM ACCEL_DB.OBSERVABILITY.TABLE_SNAPSHOTS s
                 WHERE s.SNAPSHOT_TS = :ts AND s.SCHEMA_NAME = i.SCHEMA_NAME AND s.TABLE_NAME = i.TABLE_NAME)
     AND NOT EXISTS (SELECT 1 FROM ACCEL_DB.OBSERVABILITY.TMP_CANDIDATES c
                     WHERE c.SCHEMA_NAME = i.SCHEMA_NAME AND c.TABLE_NAME = i.TABLE_NAME
                       AND c.MONITOR_TYPE = i.MONITOR_TYPE);
  n_resolved := SQLROWCOUNT;

  SELECT COUNT(*) INTO :n_open FROM ACCEL_DB.OBSERVABILITY.INCIDENTS WHERE STATUS IN ('OPEN', 'ACKNOWLEDGED');
  DROP TABLE IF EXISTS ACCEL_DB.OBSERVABILITY.TMP_CANDIDATES;
  RETURN n_new || ' new incidents, ' || n_resolved || ' auto-resolved, ' || n_open || ' open';
END;
$$;

-- Manual workflow for the dashboard / SQL users
CREATE OR REPLACE PROCEDURE SET_INCIDENT_STATUS(P_INCIDENT_ID NUMBER, P_STATUS VARCHAR, P_NOTE VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
  UPDATE ACCEL_DB.OBSERVABILITY.INCIDENTS
     SET STATUS          = UPPER(:P_STATUS),
         RESOLVED_AT     = IFF(UPPER(:P_STATUS) = 'RESOLVED', CURRENT_TIMESTAMP(), NULL),
         RESOLVED_BY     = IFF(UPPER(:P_STATUS) = 'RESOLVED', CURRENT_USER(), NULL),
         RESOLUTION_NOTE = :P_NOTE
   WHERE INCIDENT_ID = :P_INCIDENT_ID
     AND UPPER(:P_STATUS) IN ('OPEN', 'ACKNOWLEDGED', 'RESOLVED');
  RETURN SQLROWCOUNT || ' incident(s) updated (status must be OPEN, ACKNOWLEDGED or RESOLVED)';
END;
$$;

-- Latest status per monitored table
CREATE OR REPLACE VIEW V_TABLE_HEALTH AS
WITH latest AS (
  SELECT * FROM TABLE_SNAPSHOTS
  QUALIFY ROW_NUMBER() OVER (PARTITION BY SCHEMA_NAME, TABLE_NAME ORDER BY SNAPSHOT_TS DESC) = 1
),
open_inc AS (
  SELECT SCHEMA_NAME, TABLE_NAME,
         COUNT(*) AS OPEN_INCIDENTS,
         MIN(CASE SEVERITY WHEN 'CRITICAL' THEN 1 WHEN 'HIGH' THEN 2 WHEN 'MEDIUM' THEN 3 ELSE 4 END) AS WORST_RANK,
         LISTAGG(DISTINCT MONITOR_TYPE, ', ') AS OPEN_MONITORS
  FROM INCIDENTS WHERE STATUS IN ('OPEN', 'ACKNOWLEDGED')
  GROUP BY 1, 2
)
SELECT m.SCHEMA_NAME, m.TABLE_NAME, m.OWNER, m.ENABLED,
       l.SNAPSHOT_TS AS LAST_CHECKED, l.TABLE_EXISTS, l.ROW_COUNT, l.BYTES, l.LAST_ALTERED,
       DATEDIFF('minute', l.LAST_ALTERED, CURRENT_TIMESTAMP()) AS MINUTES_SINCE_CHANGE,
       m.FRESHNESS_SLA_MINUTES, m.MIN_ROWS, m.MAX_ROW_CHANGE_PCT, l.COLUMN_COUNT,
       COALESCE(o.OPEN_INCIDENTS, 0) AS OPEN_INCIDENTS, o.OPEN_MONITORS,
       CASE WHEN l.SNAPSHOT_TS IS NULL THEN 'NOT CHECKED'
            WHEN o.WORST_RANK IS NULL THEN 'HEALTHY'
            WHEN o.WORST_RANK = 1 THEN 'CRITICAL'
            WHEN o.WORST_RANK = 2 THEN 'HIGH'
            ELSE 'WARNING' END AS HEALTH
FROM MONITOR_CONFIG m
LEFT JOIN latest l   ON l.SCHEMA_NAME = m.SCHEMA_NAME AND l.TABLE_NAME = m.TABLE_NAME
LEFT JOIN open_inc o ON o.SCHEMA_NAME = m.SCHEMA_NAME AND o.TABLE_NAME = m.TABLE_NAME;

CREATE OR REPLACE VIEW V_INCIDENT_SUMMARY AS
SELECT DATE_TRUNC('day', DETECTED_AT)::DATE AS DETECTED_DATE, MONITOR_TYPE, SEVERITY, STATUS, COUNT(*) AS INCIDENTS
FROM INCIDENTS
GROUP BY 1, 2, 3, 4;

-- Account-wide DDL activity in ACCEL_DB over 7 days (ACCOUNT_USAGE, up to ~3 h lag):
-- created, dropped and altered tables, plus dropped columns. Catches changes to
-- tables not yet in MONITOR_CONFIG.
CREATE OR REPLACE VIEW V_DDL_ACTIVITY_7D AS
SELECT 'TABLE' AS OBJECT_LEVEL, TABLE_SCHEMA AS SCHEMA_NAME, TABLE_NAME, NULL AS COLUMN_NAME,
       CASE WHEN DELETED IS NOT NULL THEN 'DROPPED'
            WHEN CREATED >= DATEADD('day', -7, CURRENT_TIMESTAMP()) THEN 'CREATED'
            ELSE 'ALTERED' END AS CHANGE_TYPE,
       COALESCE(DELETED, LAST_DDL, CREATED) AS CHANGED_AT, LAST_DDL_BY AS CHANGED_BY
FROM SNOWFLAKE.ACCOUNT_USAGE.TABLES
WHERE TABLE_CATALOG = 'ACCEL_DB'
  AND (DELETED >= DATEADD('day', -7, CURRENT_TIMESTAMP())
       OR CREATED >= DATEADD('day', -7, CURRENT_TIMESTAMP())
       OR LAST_DDL >= DATEADD('day', -7, CURRENT_TIMESTAMP()))
UNION ALL
SELECT 'COLUMN', TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME, 'COLUMN DROPPED', DELETED, NULL
FROM SNOWFLAKE.ACCOUNT_USAGE.COLUMNS
WHERE TABLE_CATALOG = 'ACCEL_DB' AND DELETED >= DATEADD('day', -7, CURRENT_TIMESTAMP());

-- Hourly evaluation (created suspended)
CREATE OR REPLACE TASK TASK_OBS_EVALUATE
  WAREHOUSE = ACCEL_WH
  SCHEDULE = '60 MINUTE'                                      -- EDIT ME
AS
  CALL ACCEL_DB.OBSERVABILITY.EVALUATE_MONITORS();
