/* =============================================================================
   09 AI GOVERNANCE CONTROLS | 01_ai_usage_views.sql
   Who uses which AI function / model, how much, and at what cost.
   Sources (SNOWFLAKE.ACCOUNT_USAGE, latency up to a few hours):
     CORTEX_AI_FUNCTIONS_USAGE_HISTORY  - all Cortex AI functions (credits, user, roles, query tag)
     CORTEX_AISQL_USAGE_HISTORY         - tokens per query for AI SQL functions
     CORTEX_ANALYST_USAGE_HISTORY, CORTEX_AGENT_USAGE_HISTORY, METERING_DAILY_HISTORY
   Run as: ACCEL_ADMIN.
============================================================================= */
USE ROLE ACCEL_ADMIN;
USE WAREHOUSE ACCEL_WH;
USE DATABASE ACCEL_DB;
CREATE SCHEMA IF NOT EXISTS AI_GOVERNANCE;
USE SCHEMA AI_GOVERNANCE;

-- Credits per day x user x primary role x function x model
CREATE OR REPLACE VIEW V_AI_USAGE_BY_USER_MODEL AS
SELECT DATE_TRUNC('day', h.START_TIME)::DATE      AS USAGE_DATE,
       COALESCE(u.NAME, h.USER_ID)                AS USER_NAME,
       h.ROLE_NAMES[0]::STRING                    AS PRIMARY_ROLE,
       h.FUNCTION_NAME,
       COALESCE(NULLIF(h.MODEL_NAME, ''), '(default)') AS MODEL_NAME,
       h.QUERY_TAG,
       COUNT(DISTINCT h.QUERY_ID)                 AS QUERIES,
       SUM(h.CREDITS)                             AS CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AI_FUNCTIONS_USAGE_HISTORY h
LEFT JOIN SNOWFLAKE.ACCOUNT_USAGE.USERS u ON TO_VARCHAR(u.USER_ID) = h.USER_ID
WHERE h.START_TIME >= DATEADD('day', -90, CURRENT_TIMESTAMP())
GROUP BY 1, 2, 3, 4, 5, 6;

-- Tokens per day x user x function x model (AI SQL functions)
CREATE OR REPLACE VIEW V_AI_TOKENS_BY_USER_MODEL AS
SELECT DATE_TRUNC('day', h.USAGE_TIME)::DATE      AS USAGE_DATE,
       COALESCE(u.NAME, h.USER_ID)                AS USER_NAME,
       h.FUNCTION_NAME,
       h.MODEL_NAME,
       COUNT(DISTINCT h.QUERY_ID)                 AS QUERIES,
       SUM(h.TOKENS)                              AS TOKENS,
       SUM(h.TOKEN_CREDITS)                       AS TOKEN_CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AISQL_USAGE_HISTORY h
LEFT JOIN SNOWFLAKE.ACCOUNT_USAGE.USERS u ON TO_VARCHAR(u.USER_ID) = h.USER_ID
WHERE h.USAGE_TIME >= DATEADD('day', -90, CURRENT_TIMESTAMP())
GROUP BY 1, 2, 3, 4;

-- Conversational AI services by user
CREATE OR REPLACE VIEW V_AI_ASSISTANT_USAGE_BY_USER AS
SELECT DATE_TRUNC('day', START_TIME)::DATE AS USAGE_DATE, 'CORTEX_ANALYST' AS SERVICE,
       USERNAME AS USER_NAME, NULL AS OBJECT_NAME,
       SUM(REQUEST_COUNT) AS REQUESTS, NULL AS TOKENS, SUM(CREDITS) AS CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_ANALYST_USAGE_HISTORY
WHERE START_TIME >= DATEADD('day', -90, CURRENT_TIMESTAMP())
GROUP BY 1, 2, 3, 4
UNION ALL
SELECT DATE_TRUNC('day', START_TIME)::DATE, 'CORTEX_AGENT',
       USER_NAME, AGENT_DATABASE_NAME || '.' || AGENT_SCHEMA_NAME || '.' || AGENT_NAME,
       COUNT(DISTINCT REQUEST_ID), SUM(TOKENS), SUM(TOKEN_CREDITS)
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AGENT_USAGE_HISTORY
WHERE START_TIME >= DATEADD('day', -90, CURRENT_TIMESTAMP())
GROUP BY 1, 2, 3, 4;

-- Daily AI services credits billed (all AI features)
CREATE OR REPLACE VIEW V_AI_CREDITS_DAILY AS
SELECT USAGE_DATE, SERVICE_TYPE, SUM(CREDITS_USED) AS CREDITS_USED, SUM(CREDITS_BILLED) AS CREDITS_BILLED
FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_DAILY_HISTORY
WHERE SERVICE_TYPE IN ('AI_SERVICES', 'CORTEX_CODE_CLI', 'CORTEX_CODE_SNOWSIGHT')
  AND USAGE_DATE >= DATEADD('day', -90, CURRENT_DATE())
GROUP BY 1, 2;

-- Top AI consumers in the last 30 days
CREATE OR REPLACE VIEW V_AI_TOP_USERS_30D AS
SELECT USER_NAME, PRIMARY_ROLE,
       COUNT(DISTINCT MODEL_NAME) AS MODELS_USED,
       SUM(QUERIES)               AS QUERIES,
       SUM(CREDITS)               AS CREDITS
FROM V_AI_USAGE_BY_USER_MODEL
WHERE USAGE_DATE >= DATEADD('day', -30, CURRENT_DATE())
GROUP BY 1, 2;

GRANT USAGE ON SCHEMA ACCEL_DB.AI_GOVERNANCE TO ROLE ACCEL_ANALYST;
GRANT SELECT ON ALL VIEWS IN SCHEMA ACCEL_DB.AI_GOVERNANCE TO ROLE ACCEL_ANALYST;

SELECT * FROM V_AI_TOP_USERS_30D ORDER BY CREDITS DESC LIMIT 20;
SELECT MODEL_NAME, FUNCTION_NAME, SUM(CREDITS) AS CREDITS, SUM(QUERIES) AS QUERIES
FROM V_AI_USAGE_BY_USER_MODEL
GROUP BY 1, 2 ORDER BY CREDITS DESC;
